function MarkdownRenderer({ content }: { content: string }) {
  // Utility: convert repo-relative coverImage path to public URL path
  // Skip the leading H1 from the markdown body
  const lines = content.split(/\r?\n/);

  // Find first non-empty line
  let start = 0;
  while (start < lines.length && lines[start].trim() === '') start++;
  if (start < lines.length && /^#\s+/.test(lines[start])) {
    start++;
    // Skip a single following blank line after H1 if present
    if (start < lines.length && lines[start].trim() === '') start++;
  }

  const blocks: React.ReactNode[] = [];

  const renderInline = (text: string, keyPrefix: string) => {
    // Tokenize links, code, bold, italics in a single pass
    const pattern = /(\[[^\]]+\]\([^\)]+\))|(`[^`]+`)|(\*\*[^*]+\*\*)|(\*[^*]+\*)/g;
    const nodes: React.ReactNode[] = [];
    let lastIndex = 0;
    let m: RegExpExecArray | null;
    let i = 0;
    while ((m = pattern.exec(text)) !== null) {
      if (m.index > lastIndex) {
        nodes.push(text.slice(lastIndex, m.index));
      }
      const token = m[0];
      if (token.startsWith('`')) {
        nodes.push(
          <code key={`${keyPrefix}-code-${i++}`} className="bg-gray-100 rounded px-1 py-0.5 font-mono text-sm">
            {token.slice(1, -1)}
          </code>
        );
      } else if (token.startsWith('**')) {
        nodes.push(
          <strong key={`${keyPrefix}-b-${i++}`} className="font-semibold">{token.slice(2, -2)}</strong>
        );
      } else if (token.startsWith('*')) {
        nodes.push(
          <em key={`${keyPrefix}-i-${i++}`} className="italic">{token.slice(1, -1)}</em>
        );
      } else if (token.startsWith('[')) {
        const linkMatch = token.match(/^\[([^\]]+)\]\(([^)]+)\)$/);
        if (linkMatch) {
          const [, label, href] = linkMatch;
          nodes.push(
            <a key={`${keyPrefix}-a-${i++}`} href={href} className="text-blue-600 underline hover:no-underline" rel="noopener noreferrer" target={href.startsWith('http') ? '_blank' : undefined}>
              {label}
            </a>
          );
        } else {
          nodes.push(token);
        }
      } else {
        nodes.push(token);
      }
      lastIndex = pattern.lastIndex;
    }
    if (lastIndex < text.length) nodes.push(text.slice(lastIndex));
    return nodes;
  };

  const parseTable = (startIndex: number) => {
    const headerLine = lines[startIndex];
    const sepLine = lines[startIndex + 1] || '';
    // Validate table separator line (dashes and pipes)
    const isSep = /^\s*\|?\s*:?-{3,}:?(\s*\|\s*:?-{3,}:?)+\s*\|?\s*$/.test(sepLine);
    if (!headerLine.includes('|') || !isSep) return null;

    const rows: string[][] = [];

    const splitRow = (line: string) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((c) => c.trim());

    const headers = splitRow(headerLine);
    let r = startIndex + 2;
    while (r < lines.length && lines[r].includes('|')) {
      const row = splitRow(lines[r]);
      rows.push(row);
      r++;
    }

    const tableEl = (
      <div key={`tbl-${startIndex}`} className="my-6 overflow-x-auto">
        <table className="w-full border-collapse text-sm">
          <thead>
            <tr>
              {headers.map((h, i) => (
                <th key={`th-${i}`} scope="col" className="border px-3 py-2 text-left font-semibold bg-gray-50">{h}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row, ri) => (
              <tr key={`tr-${ri}`}>
                {row.map((cell, ci) => (
                  <td key={`td-${ri}-${ci}`} className="border px-3 py-2 align-top">{cell}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );

    return { element: tableEl, nextIndex: r };
  };

  let i = start;
  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    if (trimmed === '') { i++; continue; }

    // Headings
    const h3 = trimmed.match(/^###\s+(.+)$/);
    if (h3) {
      blocks.push(<h3 key={`h3-${i}`} className="text-xl font-semibold mt-8 mb-3">{h3[1]}</h3>);
      i++;
      continue;
    }
    const h2 = trimmed.match(/^##\s+(.+)$/);
    if (h2) {
      blocks.push(<h2 key={`h2-${i}`} className="text-2xl font-bold mt-10 mb-4">{h2[1]}</h2>);
      i++;
      continue;
    }

    // Horizontal rule
    if (/^-{3,}\s*$/.test(trimmed)) {
      blocks.push(<hr key={`hr-${i}`} className="my-8 border-gray-200" />);
      i++;
      continue;
    }

    // Table
    const tableParse = parseTable(i);
    if (tableParse) {
      blocks.push(tableParse.element);
      i = tableParse.nextIndex;
      continue;
    }

    // Blockquote (gather consecutive)
    if (/^>\s?/.test(trimmed)) {
      const quoteLines: string[] = [];
      while (i < lines.length && /^>\s?/.test(lines[i].trim())) {
        quoteLines.push(lines[i].replace(/^>\s?/, ''));
        i++;
      }
      const quoteText = quoteLines.join(' ').trim();
      blocks.push(
        <blockquote key={`bq-${i}`} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-800">
          {renderInline(quoteText, `bqi-${i}`)}
        </blockquote>
      );
      continue;
    }

    // Unordered list
    if (/^[-\*]\s+/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^[-\*]\s+/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^[-\*]\s+/, ''));
        i++;
      }
      blocks.push(
        <ul key={`ul-${i}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`uli-${idx}`}>{renderInline(it, `uli-${idx}`)}</li>
          ))}
        </ul>
      );
      continue;
    }

    // Ordered list
    if (/^\d+\.\s+/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^\d+\.\s+/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^\d+\.\s+/, ''));
        i++;
      }
      blocks.push(
        <ol key={`ol-${i}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`}>{renderInline(it, `oli-${idx}`)}</li>
          ))}
        </ol>
      );
      continue;
    }

    // Paragraph (gather until blank line)
    const paraLines: string[] = [];
    while (i < lines.length && lines[i].trim() !== '') {
      // Stop paragraph if next block starts (simple lookahead)
      if (/^###\s+/.test(lines[i]) || /^##\s+/.test(lines[i]) || /^>\s?/.test(lines[i]) || /^\d+\.\s+/.test(lines[i]) || /^[-\*]\s+/.test(lines[i]) || /\|/.test(lines[i])) {
        break;
      }
      paraLines.push(lines[i]);
      i++;
    }
    if (paraLines.length > 0) {
      const text = paraLines.join(' ').trim();
      if (text) {
        blocks.push(
          <p key={`p-${i}`} className="mb-4 leading-relaxed text-gray-900">{renderInline(text, `p-${i}`)}</p>
        );
        continue;
      }
    }

    // Fallback increment to avoid infinite loop
    i++;
  }

  return <div>{blocks}</div>;
}


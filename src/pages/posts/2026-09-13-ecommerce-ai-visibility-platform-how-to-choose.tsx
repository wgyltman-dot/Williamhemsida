function renderInline(text: string): Array<string | JSX.Element> {
  const elements: Array<string | JSX.Element> = [];
  const regex = /(\[[^\]]+\]\([^\)]+\)|\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`)/g;
  let lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      elements.push(text.slice(lastIndex, match.index));
    }
    const token = match[0];
    if (token.startsWith('[')) {
      const linkMatch = token.match(/^\[([^\]]+)\]\(([^\)]+)\)$/);
      if (linkMatch) {
        const [, label, href] = linkMatch;
        elements.push(
          <a key={`${label}-${match.index}`} href={href} className="text-blue-600 underline hover:text-blue-800 focus:outline-none focus:ring-2 focus:ring-blue-400" rel="noopener noreferrer">
            {label}
          </a>
        );
      } else {
        elements.push(token);
      }
    } else if (token.startsWith('**')) {
      elements.push(
        <strong key={`b-${match.index}`}>{token.slice(2, -2)}</strong>
      );
    } else if (token.startsWith('*')) {
      elements.push(
        <em key={`i-${match.index}`}>{token.slice(1, -1)}</em>
      );
    } else if (token.startsWith('`')) {
      elements.push(
        <code key={`c-${match.index}`} className="px-1 py-0.5 rounded bg-gray-100 text-gray-800">
          {token.slice(1, -1)}
        </code>
      );
    }
    lastIndex = regex.lastIndex;
  }
  if (lastIndex < text.length) {
    elements.push(text.slice(lastIndex));
  }
  return elements;
}

function isTableSeparator(line: string): boolean {
  const t = line.trim();
  if (!t.includes('|')) return false;
  return /^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$/.test(t);
}

function parseTable(lines: string[], start: number) {
  const rows: string[][] = [];
  let i = start;
  while (i < lines.length && lines[i].trim().length > 0 && lines[i].includes('|')) {
    rows.push(
      lines[i]
        .trim()
        .replace(/^\|/, '')
        .replace(/\|$/, '')
        .split('|')
        .map((c) => c.trim())
    );
    i++;
  }
  let header: string[] | undefined;
  let body: string[][] = rows;
  if (rows.length >= 2 && isTableSeparator(lines[start + 1])) {
    header = rows[0];
    body = rows.slice(2);
  }
  return { end: i, header, body, hasHeader: !!header };
}

function MarkdownRenderer({ content }: { content: string }) {
  const lines = content.replace(/\r\n/g, '\n').split('\n');

  // Skip leading H1 if present
  let startIndex = 0;
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i].trim();
    if (t.length === 0) continue;
    if (/^#\s+/.test(t)) {
      startIndex = i + 1;
    }
    break;
  }

  const elements: JSX.Element[] = [];
  let i = startIndex;
  let paraBuffer: string[] = [];
  let listType: 'ul' | 'ol' | null = null;
  let listItems: string[] = [];

  const flushParagraph = () => {
    if (paraBuffer.length > 0) {
      const text = paraBuffer.join(' ').trim();
      if (text.length > 0) {
        elements.push(
          <p key={`p-${elements.length}`} className="mb-4 leading-relaxed">
            {renderInline(text)}
          </p>
        );
      }
      paraBuffer = [];
    }
  };

  const flushList = () => {
    if (listType && listItems.length > 0) {
      const ListTag = listType === 'ul' ? 'ul' : 'ol';
      elements.push(
        <ListTag key={`list-${elements.length}`} className={listType === 'ul' ? 'list-disc pl-6 mb-4 space-y-2' : 'list-decimal pl-6 mb-4 space-y-2'}>
          {listItems.map((item, idx) => (
            <li key={`li-${idx}`}>{renderInline(item)}</li>
          ))}
        </ListTag>
      );
    }
    listType = null;
    listItems = [];
  };

  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    // Table block
    if (trimmed.includes('|') && !trimmed.startsWith('>') && !/^#{1,6}\s/.test(trimmed)) {
      // Peek ahead to ensure it's actually a table (at least two pipes)
      const pipeCount = (trimmed.match(/\|/g) || []).length;
      if (pipeCount >= 2) {
        flushParagraph();
        flushList();
        const { end, header, body } = parseTable(lines, i);
        elements.push(
          <div key={`table-${elements.length}`} className="w-full overflow-x-auto my-6">
            <table className="w-full border-collapse">
              {header ? (
                <thead>
                  <tr>
                    {header.map((h, idx) => (
                      <th key={`th-${idx}`} scope="col" className="border px-3 py-2 text-left font-semibold">
                        {renderInline(h)}
                      </th>
                    ))}
                  </tr>
                </thead>
              ) : null}
              <tbody>
                {body.map((row, rIdx) => (
                  <tr key={`tr-${rIdx}`}>
                    {row.map((cell, cIdx) => (
                      <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left">
                        {renderInline(cell)}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        );
        i = end;
        continue;
      }
    }

    // Horizontal rule
    if (/^\s*(-{3,}|\*{3,})\s*$/.test(trimmed)) {
      flushParagraph();
      flushList();
      elements.push(<hr key={`hr-${elements.length}`} className="my-8 border-t" />);
      i++;
      continue;
    }

    // Headings
    const hMatch = trimmed.match(/^(#{1,6})\s+(.*)$/);
    if (hMatch) {
      flushParagraph();
      flushList();
      const level = Math.min(hMatch[1].length, 6);
      const text = hMatch[2].trim();
      const common = level === 2
        ? 'text-2xl font-bold mt-10 mb-4'
        : level === 3
        ? 'text-xl font-semibold mt-8 mb-3'
        : level === 4
        ? 'text-lg font-semibold mt-6 mb-3'
        : 'text-base font-semibold mt-6 mb-3';
      const HeadingTag = (`h${Math.min(level, 6)}` as keyof JSX.IntrinsicElements);
      // If a stray H1 appears later, render it as H2 for hierarchy
      const adjustedTag = level === 1 ? ('h2' as const) : (HeadingTag as const);
      elements.push(
        React.createElement(
          adjustedTag,
          { key: `h-${elements.length}`, className: common },
          renderInline(text)
        )
      );
      i++;
      continue;
    }

    // Blockquote
    if (trimmed.startsWith('>')) {
      flushParagraph();
      flushList();
      const quoteLines: string[] = [];
      while (i < lines.length && lines[i].trim().startsWith('>')) {
        quoteLines.push(lines[i].trim().replace(/^>\s?/, ''));
        i++;
      }
      const quoteText = quoteLines.join(' ').trim();
      elements.push(
        <blockquote key={`q-${elements.length}`} className="border-l-4 pl-4 italic my-6 text-gray-700">
          {renderInline(quoteText)}
        </blockquote>
      );
      continue;
    }

    // Lists
    const ulMatch = trimmed.match(/^[-•]\s+(.*)$/);
    const olMatch = trimmed.match(/^(\d+)\.\s+(.*)$/);
    if (ulMatch) {
      flushParagraph();
      if (listType === 'ol') flushList();
      listType = 'ul';
      listItems.push(ulMatch[1]);
      i++;
      // Continue collecting list items
      while (i < lines.length) {
        const t = lines[i].trim();
        const m = t.match(/^[-•]\s+(.*)$/);
        if (m) {
          listItems.push(m[1]);
          i++;
        } else {
          break;
        }
      }
      flushList();
      continue;
    }
    if (olMatch) {
      flushParagraph();
      if (listType === 'ul') flushList();
      listType = 'ol';
      listItems.push(olMatch[2]);
      i++;
      while (i < lines.length) {
        const t = lines[i].trim();
        const m = t.match(/^(\d+)\.\s+(.*)$/);
        if (m) {
          listItems.push(m[2]);
          i++;
        } else {
          break;
        }
      }
      flushList();
      continue;
    }

    // Blank line -> paragraph break
    if (trimmed.length === 0) {
      flushParagraph();
      i++;
      continue;
    }

    // Default: part of a paragraph
    paraBuffer.push(trimmed);
    i++;
  }

  // Flush any trailing buffers
  flushList();
  flushParagraph();

  return <div>{elements}</div>;
}


function renderInline(text: string): ReactNode[] {
  const nodes: ReactNode[] = []

  // Step 1: Extract code spans to placeholders
  type Segment = { type: 'text' | 'code'; value: string }
  const codeSplit: Segment[] = []
  const parts = text.split(/(`[^`]*`)/g)
  for (const p of parts) {
    if (p.startsWith('`') && p.endsWith('`')) {
      codeSplit.push({ type: 'code', value: p.slice(1, -1) })
    } else if (p) {
      codeSplit.push({ type: 'text', value: p })
    }
  }

  let key = 0
  const pushNode = (n: ReactNode) => nodes.push(n)

  for (const seg of codeSplit) {
    if (seg.type === 'code') {
      pushNode(
        <code key={`code-${key++}`} className="px-1 py-0.5 rounded bg-gray-100 text-gray-800">
          {seg.value}
        </code>
      )
      continue
    }

    // Links [text](url)
    const linkParts = seg.value.split(/(\[[^\]]+\]\([^\s)]+\))/g)
    for (const lp of linkParts) {
      if (/^\[[^\]]+\]\([^\s)]+\)$/.test(lp)) {
        const m = lp.match(/^\[([^\]]+)\]\(([^\s)]+)\)$/)
        if (m) {
          const [, label, href] = m
          pushNode(
            <a key={`a-${key++}`} href={href} className="text-blue-600 underline hover:text-blue-800" target="_blank" rel="noopener noreferrer">
              {label}
            </a>
          )
          continue
        }
      }
      // Bold **text**
      const boldSplit = lp.split(/(\*\*[^*]+\*\*)/g)
      for (const bs of boldSplit) {
        if (/^\*\*[^*]+\*\*$/.test(bs)) {
          pushNode(
            <strong key={`b-${key++}`} className="font-semibold">
              {bs.slice(2, -2)}
            </strong>
          )
          continue
        }
        // Italic *text*
        const italicSplit = bs.split(/(\*[^*]+\*)/g)
        for (const is of italicSplit) {
          if (/^\*[^*]+\*$/.test(is)) {
            pushNode(<em key={`i-${key++}`} className="italic">{is.slice(1, -1)}</em>)
          } else if (is) {
            pushNode(<span key={`t-${key++}`}>{is}</span>)
          }
        }
      }
    }
  }

  return nodes
}

function MarkdownRenderer({ content }: { content: string }) {
  // Remove leading H1 if present
  const lines = content.replace(/\r\n?/g, '\n').split('\n')
  let idx = 0
  // Skip initial empty lines
  while (idx < lines.length && lines[idx].trim() === '') idx++
  if (idx < lines.length && /^#\s+/.test(lines[idx])) idx++

  const elements: ReactNode[] = []
  let key = 0

  function flushParagraph(paragraphLines: string[]) {
    if (paragraphLines.length === 0) return
    const text = paragraphLines.join(' ').trim()
    if (text) {
      elements.push(
        <p key={`p-${key++}`} className="mb-4 leading-relaxed">
          {renderInline(text)}
        </p>
      )
    }
  }

  while (idx < lines.length) {
    const line = lines[idx]

    // Horizontal rule
    if (/^\s*---\s*$/.test(line)) {
      elements.push(<hr key={`hr-${key++}`} className="my-8 border-t" />)
      idx++
      continue
    }

    // Headings
    if (/^###\s+/.test(line)) {
      const text = line.replace(/^###\s+/, '')
      elements.push(
        <h3 key={`h3-${key++}`} className="text-xl font-semibold mt-8 mb-3">
          {renderInline(text)}
        </h3>
      )
      idx++
      continue
    }
    if (/^##\s+/.test(line)) {
      const text = line.replace(/^##\s+/, '')
      elements.push(
        <h2 key={`h2-${key++}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(text)}
        </h2>
      )
      idx++
      continue
    }

    // Blockquote
    if (/^>\s?/.test(line)) {
      const quoteLines: string[] = []
      while (idx < lines.length && /^>\s?/.test(lines[idx])) {
        quoteLines.push(lines[idx].replace(/^>\s?/, ''))
        idx++
      }
      const text = quoteLines.join(' ').trim()
      elements.push(
        <blockquote key={`bq-${key++}`} className="border-l-4 pl-4 italic my-6 text-gray-700">
          {renderInline(text)}
        </blockquote>
      )
      continue
    }

    // Tables (pipe tables)
    if (line.includes('|')) {
      // Peek next line to check for header separator
      const next = lines[idx + 1] ?? ''
      if (/^\s*\|?\s*:?-{3,}\s*(\|\s*:?-{3,}\s*)+\|?\s*$/.test(next) || /^\s*\|\s*-{3,}\s*(\|\s*-{3,}\s*)+\|?\s*$/.test(next) || /^\s*-{3,}\s*\|/.test(next)) {
        const tableLines: string[] = []
        // collect contiguous lines with pipes
        while (idx < lines.length && lines[idx].includes('|') && lines[idx].trim() !== '') {
          tableLines.push(lines[idx])
          idx++
        }
        if (tableLines.length >= 2) {
          const header = tableLines[0]
          const rows = tableLines.slice(2)
          const splitRow = (r: string) => r.split('|').filter((c, i, a) => !(i === 0 && c.trim() === '') && !(i === a.length - 1 && c.trim() === '')).map(c => c.trim())
          const headers = splitRow(header)
          const bodyRows = rows.map(splitRow).filter(r => r.length > 0)
          elements.push(
            <div key={`tblwrap-${key++}`} className="my-6 overflow-x-auto">
              <table className="w-full border-collapse my-6 min-w-max">
                <thead>
                  <tr>
                    {headers.map((h, i) => (
                      <th key={`th-${i}`} className="border px-3 py-2 text-left bg-gray-50 font-semibold">{renderInline(h)}</th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {bodyRows.map((r, ri) => (
                    <tr key={`tr-${ri}`} className={ri % 2 === 0 ? 'bg-white' : 'bg-gray-50'}>
                      {r.map((c, ci) => (
                        <td key={`td-${ri}-${ci}`} className="border px-3 py-2 align-top">{renderInline(c)}</td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )
          continue
        }
      }
    }

    // Lists
    if (/^\s*[-*+]\s+/.test(line)) {
      const items: string[] = []
      while (idx < lines.length && /^\s*[-*+]\s+/.test(lines[idx])) {
        items.push(lines[idx].replace(/^\s*[-*+]\s+/, ''))
        idx++
      }
      elements.push(
        <ul key={`ul-${key++}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, i) => (
            <li key={`li-u-${i}`}>{renderInline(it)}</li>
          ))}
        </ul>
      )
      continue
    }
    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = []
      while (idx < lines.length && /^\s*\d+\.\s+/.test(lines[idx])) {
        items.push(lines[idx].replace(/^\s*\d+\.\s+/, ''))
        idx++
      }
      elements.push(
        <ol key={`ol-${key++}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, i) => (
            <li key={`li-o-${i}`}>{renderInline(it)}</li>
          ))}
        </ol>
      )
      continue
    }

    // Paragraphs and blank lines
    if (line.trim() === '') {
      idx++
      continue
    }
    const paraLines: string[] = []
    while (idx < lines.length && lines[idx].trim() !== '') {
      // Stop paragraph if next line would start a block element
      if (/^(###|##|>\s|\s*[-*+]\s+|\s*\d+\.\s+|\s*---\s*$)/.test(lines[idx])) break
      if (lines[idx].includes('|')) break
      paraLines.push(lines[idx])
      idx++
    }
    flushParagraph(paraLines)
  }

  return <div>{elements}</div>
}


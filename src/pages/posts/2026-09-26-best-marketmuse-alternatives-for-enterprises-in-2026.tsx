function formatDate(iso: string) {
  try {
    return new Date(iso).toLocaleDateString(undefined, {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    })
  } catch {
    return iso
  }
}

function MarkdownRenderer({ content }: { content: string }) {
  // Parse markdown into elements, skipping the leading H1 if present
  const elements: React.ReactNode[] = []
  const lines = content.split('\n')

  // Skip leading H1 if the first non-empty line is a single '# '
  let i = 0
  let firstNonEmpty = -1
  for (let idx = 0; idx < lines.length; idx++) {
    if (lines[idx].trim().length > 0) {
      firstNonEmpty = idx
      break
    }
  }
  if (firstNonEmpty >= 0 && lines[firstNonEmpty].startsWith('# ')) {
    // Skip this line
    i = firstNonEmpty + 1
  }

  function renderInline(text: string): (string | JSX.Element)[] {
    const out: (string | JSX.Element)[] = []
    let buf = ''

    const flush = () => {
      if (buf) {
        out.push(buf)
        buf = ''
      }
    }

    const len = text.length
    let p = 0
    while (p < len) {
      // Code span
      if (text[p] === '`') {
        const end = text.indexOf('`', p + 1)
        if (end > p + 1) {
          flush()
          const codeText = text.slice(p + 1, end)
          out.push(
            <code key={`code-${p}`} className="bg-gray-100 rounded px-1 py-0.5 text-sm">
              {codeText}
            </code>
          )
          p = end + 1
          continue
        }
      }
      // Markdown link [text](url)
      if (text[p] === '[') {
        const close = text.indexOf(']', p + 1)
        if (close > p + 1 && text[close + 1] === '(') {
          const end = text.indexOf(')', close + 2)
          if (end > close + 2) {
            const label = text.slice(p + 1, close)
            const url = text.slice(close + 2, end)
            flush()
            out.push(
              <a key={`link-${p}`} href={url} target="_blank" rel="noopener noreferrer" className="text-blue-600 underline">
                {label}
              </a>
            )
            p = end + 1
            continue
          }
        }
      }
      // Auto-link http(s)
      if (text.startsWith('http://', p) || text.startsWith('https://', p)) {
        // read until whitespace or end
        let end = p
        while (end < len && !/\s/.test(text[end])) end++
        const url = text.slice(p, end)
        flush()
        out.push(
          <a key={`autolink-${p}`} href={url} target="_blank" rel="noopener noreferrer" className="text-blue-600 underline">
            {url}
          </a>
        )
        p = end
        continue
      }
      // Bold **text**
      if (text[p] === '*' && text[p + 1] === '*') {
        const end = text.indexOf('**', p + 2)
        if (end > p + 2) {
          const boldText = text.slice(p + 2, end)
          flush()
          out.push(
            <strong key={`bold-${p}`} className="font-semibold">
              {renderInline(boldText)}
            </strong>
          )
          p = end + 2
          continue
        }
      }
      // Italic *text*
      if (text[p] === '*') {
        const end = text.indexOf('*', p + 1)
        if (end > p + 1) {
          const emText = text.slice(p + 1, end)
          flush()
          out.push(
            <em key={`em-${p}`} className="italic">
              {renderInline(emText)}
            </em>
          )
          p = end + 1
          continue
        }
      }
      // Default: append char
      buf += text[p]
      p++
    }
    flush()
    return out
  }

  function consumeTable(start: number) {
    const rows: string[] = []
    let idx = start
    while (idx < lines.length) {
      const line = lines[idx]
      if (line.trim() === '') break
      if (line.indexOf('|') === -1) break
      rows.push(line)
      idx++
    }
    // Validate that second row is separator if present
    if (rows.length >= 2 && rows[1].includes('---')) {
      // ok
    } else {
      // Not a valid table, return single line consumption
      return { end: start + 1, node: (
        <p key={`p-${start}`} className="mb-4 leading-relaxed">
          {renderInline(lines[start])}
        </p>
      ) }
    }

    const headerLine = rows[0]
    const bodyLines = rows.slice(2)
    const splitRow = (row: string) => {
      let cells = row.split('|')
      // Trim and drop leading/trailing empties caused by pipes at edges
      cells = cells.map((c) => c.trim())
      if (cells[0] === '') cells.shift()
      if (cells[cells.length - 1] === '') cells.pop()
      return cells
    }
    const headers = splitRow(headerLine)
    const bodyRows = bodyLines.map(splitRow)

    const tableNode = (
      <div key={`table-${start}`} className="w-full overflow-x-auto my-6">
        <table className="w-full border-collapse text-sm">
          <thead>
            <tr>
              {headers.map((h, idx) => (
                <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                  {renderInline(h)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {bodyRows.map((cells, rIdx) => (
              <tr key={`tr-${rIdx}`}>
                {cells.map((c, cIdx) => (
                  <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 align-top">
                    {renderInline(c)}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    )

    return { end: start + rows.length, node: tableNode }
  }

  while (i < lines.length) {
    const line = lines[i]
    if (line.trim() === '') {
      i++
      continue
    }

    // Headings
    if (/^#{2,6} /.test(line)) {
      const level = line.match(/^#+/)?.[0].length || 2
      const text = line.replace(/^#{2,6}\s+/, '')
      if (level === 2) {
        elements.push(
          <h2 key={`h2-${i}`} className="text-2xl font-bold mt-10 mb-4">
            {renderInline(text)}
          </h2>
        )
      } else if (level === 3) {
        elements.push(
          <h3 key={`h3-${i}`} className="text-xl font-semibold mt-8 mb-3">
            {renderInline(text)}
          </h3>
        )
      } else if (level === 4) {
        elements.push(
          <h4 key={`h4-${i}`} className="text-lg font-semibold mt-6 mb-2">
            {renderInline(text)}
          </h4>
        )
      } else {
        elements.push(
          <h5 key={`h5-${i}`} className="text-base font-semibold mt-4 mb-2">
            {renderInline(text)}
          </h5>
        )
      }
      i++
      continue
    }

    // Horizontal rule
    if (/^\s*-{3,}\s*$/.test(line)) {
      elements.push(<hr key={`hr-${i}`} className="my-8 border-t" />)
      i++
      continue
    }

    // Blockquote
    if (line.startsWith('> ')) {
      const parts: string[] = []
      let j = i
      while (j < lines.length && lines[j].startsWith('> ')) {
        parts.push(lines[j].slice(2))
        j++
      }
      const quoteText = parts.join(' ')
      elements.push(
        <blockquote key={`bq-${i}`} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-700">
          {renderInline(quoteText)}
        </blockquote>
      )
      i = j
      continue
    }

    // Table
    if (line.indexOf('|') !== -1) {
      const res = consumeTable(i)
      elements.push(res.node)
      i = res.end
      continue
    }

    // Lists
    if (/^\s*[-*+]\s+/.test(line)) {
      const items: string[] = []
      let j = i
      while (j < lines.length && /^\s*[-*+]\s+/.test(lines[j])) {
        items.push(lines[j].replace(/^\s*[-*+]\s+/, ''))
        j++
      }
      elements.push(
        <ul key={`ul-${i}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`uli-${idx}`}>{renderInline(it)}</li>
          ))}
        </ul>
      )
      i = j
      continue
    }

    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = []
      let j = i
      while (j < lines.length && /^\s*\d+\.\s+/.test(lines[j])) {
        items.push(lines[j].replace(/^\s*\d+\.\s+/, ''))
        j++
      }
      elements.push(
        <ol key={`ol-${i}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`}>{renderInline(it)}</li>
          ))}
        </ol>
      )
      i = j
      continue
    }

    // Paragraph (collect until blank line)
    const para: string[] = []
    let j = i
    while (j < lines.length && lines[j].trim() !== '') {
      para.push(lines[j])
      j++
    }
    elements.push(
      <p key={`p-${i}`} className="mb-4 leading-relaxed">
        {renderInline(para.join(' '))}
      </p>
    )
    i = j
  }

  return <div>{elements}</div>
}


let inlineKey = 0;
function parseEmphasis(text: string): React.ReactNode[] {
  const strongRegex = /\*\*([^*]+)\*\*/g;
  const out: React.ReactNode[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = strongRegex.exec(text)) !== null) {
    if (m.index > last) out.push(text.slice(last, m.index));
    out.push(
      <strong key={`strong-${inlineKey++}`} className="font-semibold">{m[1]}</strong>
    );
    last = m.index + m[0].length;
  }
  const rest = text.slice(last);
  // italics within rest
  const italicsRegex = /\*([^*]+)\*/g;
  let lastI = 0;
  while ((m = italicsRegex.exec(rest)) !== null) {
    if (m.index > lastI) out.push(rest.slice(lastI, m.index));
    out.push(
      <em key={`em-${inlineKey++}`} className="italic">{m[1]}</em>
    );
    lastI = m.index + m[0].length;
  }
  if (lastI < rest.length) out.push(rest.slice(lastI));
  return out;
}

function parseStyleAndCode(text: string): React.ReactNode[] {
  const codeRegex = /`([^`]+)`/g;
  const nodes: React.ReactNode[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = codeRegex.exec(text)) !== null) {
    if (m.index > last) nodes.push(...parseEmphasis(text.slice(last, m.index)));
    nodes.push(
      <code
        key={`code-${inlineKey++}`}
        className="bg-gray-100 rounded px-1 py-0.5 font-mono text-sm"
      >
        {m[1]}
      </code>
    );
    last = m.index + m[0].length;
  }
  if (last < text.length) nodes.push(...parseEmphasis(text.slice(last)));
  return nodes;
}

function parseInline(text: string): React.ReactNode[] {
  const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  const nodes: React.ReactNode[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = linkRegex.exec(text)) !== null) {
    if (m.index > last) nodes.push(...parseStyleAndCode(text.slice(last, m.index)));
    const label = m[1];
    const href = m[2];
    const external = /^https?:\/\//.test(href);
    nodes.push(
      <a
        key={`a-${inlineKey++}`}
        href={href}
        className="text-blue-600 underline hover:text-blue-700 focus:outline-none focus:ring-2 focus:ring-blue-400 rounded"
        target={external ? '_blank' : undefined}
        rel={external ? 'noopener noreferrer' : undefined}
      >
        {label}
      </a>
    );
    last = m.index + m[0].length;
  }
  if (last < text.length) nodes.push(...parseStyleAndCode(text.slice(last)));
  return nodes;
}

function MarkdownRenderer({ markdown }: { markdown: string }) {
  const lines = markdown.split(/\r?\n/);
  // Skip the first leading H1 if present
  let firstIdx = 0;
  while (firstIdx < lines.length && lines[firstIdx].trim() === '') firstIdx++;
  if (firstIdx < lines.length && /^#\s+/.test(lines[firstIdx])) {
    lines.splice(firstIdx, 1);
  }

  const elements: React.ReactNode[] = [];
  let i = 0;

  const pushParagraph = (buffer: string[]) => {
    const text = buffer.join(' ').trim();
    if (!text) return;
    elements.push(
      <p key={`p-${i}-${inlineKey++}`} className="mb-4 leading-relaxed">
        {parseInline(text)}
      </p>
    );
  };

  while (i < lines.length) {
    const raw = lines[i];
    const line = raw; // keep original spacing minimally
    const trimmed = line.trim();

    // Blank line -> skip and move on
    if (trimmed === '') {
      i++;
      continue;
    }

    // Horizontal rule
    if (/^---$/.test(trimmed)) {
      elements.push(<hr key={`hr-${i}`} className="my-8 border-t" />);
      i++;
      continue;
    }

    // Headings (## to ######)
    const hMatch = /^(#{2,6})\s+(.+)$/.exec(trimmed);
    if (hMatch) {
      const level = hMatch[1].length;
      const content = hMatch[2];
      const common = 'mt-10 mb-4';
      if (level === 2) {
        elements.push(
          <h2 key={`h2-${i}`} className={`text-2xl font-bold ${common}`}>{parseInline(content)}</h2>
        );
      } else if (level === 3) {
        elements.push(
          <h3 key={`h3-${i}`} className="text-xl font-semibold mt-8 mb-3">{parseInline(content)}</h3>
        );
      } else if (level === 4) {
        elements.push(
          <h4 key={`h4-${i}`} className="text-lg font-semibold mt-6 mb-2">{parseInline(content)}</h4>
        );
      } else if (level === 5) {
        elements.push(
          <h5 key={`h5-${i}`} className="text-base font-semibold mt-4 mb-2">{parseInline(content)}</h5>
        );
      } else {
        elements.push(
          <h6 key={`h6-${i}`} className="text-base font-medium mt-4 mb-2">{parseInline(content)}</h6>
        );
      }
      i++;
      continue;
    }

    // Blockquote
    if (/^>\s+/.test(trimmed)) {
      const quoteLines: string[] = [];
      while (i < lines.length && /^>\s+/.test(lines[i].trim())) {
        quoteLines.push(lines[i].trim().replace(/^>\s+/, ''));
        i++;
      }
      elements.push(
        <blockquote key={`bq-${i}`} className="border-l-4 pl-4 italic my-6">
          {parseInline(quoteLines.join(' '))}
        </blockquote>
      );
      continue;
    }

    // Table (simple pipe tables)
    if (trimmed.includes('|')) {
      const start = i;
      const rows: string[] = [];
      while (i < lines.length && lines[i].trim().includes('|') && lines[i].trim() !== '') {
        rows.push(lines[i].trim());
        i++;
      }
      // Validate table (needs at least 2 rows and a separator row with ---)
      if (
        rows.length >= 2 &&
        /\|\s*-{3,}\s*(\|\s*-{3,}\s*)+\|?/.test(rows[1])
      ) {
        const headerCells = rows[0]
          .replace(/^\|\s*/, '')
          .replace(/\s*\|\s*$/, '')
          .split('|')
          .map((c) => c.trim());
        const bodyRows = rows.slice(2).map((r) =>
          r
            .replace(/^\|\s*/, '')
            .replace(/\s*\|\s*$/, '')
            .split('|')
            .map((c) => c.trim())
        );
        elements.push(
          <table key={`tbl-${start}`} className="w-full border-collapse my-6">
            <thead>
              <tr>
                {headerCells.map((h, idx) => (
                  <th key={`th-${start}-${idx}`} className="border px-3 py-2 text-left font-semibold">
                    {parseInline(h)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {bodyRows.map((r, ridx) => (
                <tr key={`tr-${start}-${ridx}`}>
                  {r.map((c, cidx) => (
                    <td key={`td-${start}-${ridx}-${cidx}`} className="border px-3 py-2 text-left">
                      {parseInline(c)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        );
        continue;
      } else {
        // Not a valid table -> fallback to paragraph rendering of collected rows
        const paragraph = rows.join(' ');
        elements.push(
          <p key={`p-${start}`} className="mb-4 leading-relaxed">
            {parseInline(paragraph)}
          </p>
        );
        continue;
      }
    }

    // Lists (unordered and ordered)
    const ulMatch = /^-\s+(.+)$/.exec(trimmed);
    const olMatch = /^(\d+)\.\s+(.+)$/.exec(trimmed);
    if (ulMatch || olMatch) {
      const items: string[] = [];
      const ordered = !!olMatch;
      while (i < lines.length) {
        const t = lines[i].trim();
        const mUl = /^-\s+(.+)$/.exec(t);
        const mOl = /^(\d+)\.\s+(.+)$/.exec(t);
        if ((ordered && mOl) || (!ordered && mUl)) {
          items.push(ordered ? (mOl as RegExpExecArray)[2] : (mUl as RegExpExecArray)[1]);
          i++;
        } else {
          break;
        }
      }
      if (ordered) {
        elements.push(
          <ol key={`ol-${i}`} className="list-decimal pl-6 mb-4 space-y-2">
            {items.map((it, idx) => (
              <li key={`oli-${i}-${idx}`}>{parseInline(it)}</li>
            ))}
          </ol>
        );
      } else {
        elements.push(
          <ul key={`ul-${i}`} className="list-disc pl-6 mb-4 space-y-2">
            {items.map((it, idx) => (
              <li key={`uli-${i}-${idx}`}>{parseInline(it)}</li>
            ))}
          </ul>
        );
      }
      continue;
    }

    // Paragraph (collect until blank line or special block)
    const paraBuf: string[] = [trimmed];
    i++;
    while (i < lines.length) {
      const t = lines[i].trim();
      if (
        t === '' ||
        /^---$/.test(t) ||
        /^#{1,6}\s+/.test(t) ||
        /^>\s+/.test(t) ||
        /^-\s+/.test(t) ||
        /^(\d+)\.\s+/.test(t) ||
        t.includes('|')
      ) {
        break;
      }
      paraBuf.push(t);
      i++;
    }
    pushParagraph(paraBuf);
  }

  return <div>{elements}</div>;
}


function MarkdownRenderer({ markdown }: { markdown: string }) {
  type Block =
    | { type: 'h2'; text: string }
    | { type: 'h3'; text: string }
    | { type: 'h4'; text: string }
    | { type: 'p'; text: string }
    | { type: 'ul'; items: string[] }
    | { type: 'ol'; items: string[] }
    | { type: 'blockquote'; text: string }
    | { type: 'hr' }
    | { type: 'table'; header: string[]; rows: string[][] }

  const lines = markdown.replace(/\r\n?/g, '\n').split('\n')

  // Skip a leading H1 line to avoid duplicate title
  let i = 0
  while (i < lines.length && lines[i].trim() === '') i++
  if (i < lines.length && /^#\s+/.test(lines[i])) {
    i++
  }

  const blocks: Block[] = []
  let paragraphBuffer: string[] = []

  const flushParagraph = () => {
    if (paragraphBuffer.length) {
      const text = paragraphBuffer.join(' ').trim()
      if (text) blocks.push({ type: 'p', text })
      paragraphBuffer = []
    }
  }

  while (i < lines.length) {
    const line = lines[i]

    // Blank line: separate paragraphs
    if (line.trim() === '') {
      flushParagraph()
      i++
      continue
    }

    // Headings
    if (/^##\s+/.test(line)) {
      flushParagraph()
      blocks.push({ type: 'h2', text: line.replace(/^##\s+/, '').trim() })
      i++
      continue
    }
    if (/^###\s+/.test(line)) {
      flushParagraph()
      blocks.push({ type: 'h3', text: line.replace(/^###\s+/, '').trim() })
      i++
      continue
    }
    if (/^####\s+/.test(line)) {
      flushParagraph()
      blocks.push({ type: 'h4', text: line.replace(/^####\s+/, '').trim() })
      i++
      continue
    }

    // Horizontal rule (ensure it's not part of a table row)
    if (/^\s*---\s*$/.test(line) && (i === 0 || !/\|/.test(lines[i - 1]))) {
      flushParagraph()
      blocks.push({ type: 'hr' })
      i++
      continue
    }

    // Blockquote
    if (/^>\s+/.test(line)) {
      flushParagraph()
      const quoteLines: string[] = []
      while (i < lines.length && /^>\s+/.test(lines[i])) {
        quoteLines.push(lines[i].replace(/^>\s+/, ''))
        i++
      }
      blocks.push({ type: 'blockquote', text: quoteLines.join(' ') })
      continue
    }

    // Unordered list
    if (/^\-\s+/.test(line)) {
      flushParagraph()
      const items: string[] = []
      while (i < lines.length && /^\-\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\-\s+/, '').trim())
        i++
      }
      blocks.push({ type: 'ul', items })
      continue
    }

    // Ordered list
    if (/^\d+\.\s+/.test(line)) {
      flushParagraph()
      const items: string[] = []
      while (i < lines.length && /^\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\d+\.\s+/, '').trim())
        i++
      }
      blocks.push({ type: 'ol', items })
      continue
    }

    // Table (group consecutive lines containing pipes)
    if (/\|/.test(line)) {
      const tableGroup: string[] = []
      while (i < lines.length && /\|/.test(lines[i])) {
        tableGroup.push(lines[i])
        i++
      }
      if (tableGroup.length >= 2) {
        const parseRow = (row: string) => {
          const parts = row.split('|').map(s => s.trim())
          // Remove possible empty first/last if markdown uses leading/trailing pipes
          if (parts.length && parts[0] === '') parts.shift()
          if (parts.length && parts[parts.length - 1] === '') parts.pop()
          return parts
        }
        const header = parseRow(tableGroup[0])
        // skip separator row (second) if it looks like --- markers
        const startIdx = /---/.test(tableGroup[1]) ? 2 : 1
        const rows = tableGroup.slice(startIdx).map(parseRow)
        flushParagraph()
        blocks.push({ type: 'table', header, rows })
        continue
      }
    }

    // Paragraph text accumulation
    paragraphBuffer.push(line.trim())
    i++
  }

  flushParagraph()

  function renderInline(text: string): React.ReactNode[] {
    const nodes: React.ReactNode[] = []
    const pattern = /(\[([^\]]+)\]\(([^)]+)\))|(\*\*([^*]+)\*\*)|(\*([^*]+)\*)|(`([^`]+)`)/g
    let lastIndex = 0
    let match: RegExpExecArray | null
    while ((match = pattern.exec(text))) {
      if (match.index > lastIndex) {
        nodes.push(text.slice(lastIndex, match.index))
      }
      if (match[1]) {
        const label = match[2]
        const url = match[3]
        nodes.push(
          <a key={`link-${lastIndex}`} href={url} className="text-blue-600 underline hover:text-blue-800" rel="noopener noreferrer" target="_blank">
            {label}
          </a>
        )
      } else if (match[4]) {
        const bold = match[5]
        nodes.push(<strong key={`b-${lastIndex}`} className="font-semibold">{bold}</strong>)
      } else if (match[6]) {
        const italic = match[7]
        nodes.push(<em key={`i-${lastIndex}`} className="italic">{italic}</em>)
      } else if (match[8]) {
        const code = match[9]
        nodes.push(<code key={`c-${lastIndex}`} className="bg-gray-100 rounded px-1 py-0.5 text-sm">{code}</code>)
      }
      lastIndex = pattern.lastIndex
    }
    if (lastIndex < text.length) {
      nodes.push(text.slice(lastIndex))
    }
    return nodes
  }

  return (
    <div>
      {blocks.map((b, idx) => {
        switch (b.type) {
          case 'h2':
            return (
              <h2 key={idx} className="text-2xl font-bold mt-10 mb-4">
                {renderInline(b.text)}
              </h2>
            )
          case 'h3':
            return (
              <h3 key={idx} className="text-xl font-semibold mt-8 mb-3">
                {renderInline(b.text)}
              </h3>
            )
          case 'h4':
            return (
              <h4 key={idx} className="text-lg font-semibold mt-6 mb-3">
                {renderInline(b.text)}
              </h4>
            )
          case 'p':
            return (
              <p key={idx} className="mb-4 leading-relaxed">
                {renderInline(b.text)}
              </p>
            )
          case 'ul':
            return (
              <ul key={idx} className="list-disc pl-6 mb-4 space-y-2">
                {b.items.map((it, i2) => (
                  <li key={i2} className="leading-relaxed">
                    {renderInline(it)}
                  </li>
                ))}
              </ul>
            )
          case 'ol':
            return (
              <ol key={idx} className="list-decimal pl-6 mb-4 space-y-2">
                {b.items.map((it, i2) => (
                  <li key={i2} className="leading-relaxed">
                    {renderInline(it)}
                  </li>
                ))}
              </ol>
            )
          case 'blockquote':
            return (
              <blockquote key={idx} className="border-l-4 pl-4 italic my-6">
                {renderInline(b.text)}
              </blockquote>
            )
          case 'hr':
            return <hr key={idx} className="my-6 border-gray-200" />
          case 'table':
            return (
              <div key={idx} className="my-6 overflow-x-auto">
                <table className="w-full border-collapse">
                  <thead>
                    <tr>
                      {b.header.map((h, i2) => (
                        <th key={i2} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                          {renderInline(h)}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {b.rows.map((row, rIdx) => (
                      <tr key={rIdx}>
                        {row.map((cell, cIdx) => (
                          <td key={cIdx} className="border px-3 py-2">
                            {renderInline(cell)}
                          </td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )
          default:
            return null
        }
      })}
    </div>
  )
}


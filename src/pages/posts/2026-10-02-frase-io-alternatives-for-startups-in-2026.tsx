function MarkdownRenderer({ content }: { content: string }) {
  const elements = React.useMemo(() => parseMarkdown(content), [content])
  return <div>{elements}</div>
}

function parseMarkdown(md: string): React.ReactNode[] {
  const lines = md.split('\n')
  const nodes: React.ReactNode[] = []
  let i = 0
  let leadingH1Skipped = false

  const pushParagraph = (paragraphLines: string[]) => {
    const text = paragraphLines.join(' ').trim()
    if (text) {
      nodes.push(
        <p key={`p-${nodes.length}`} className="mb-4 leading-relaxed">
          {renderInline(text)}
        </p>
      )
    }
  }

  while (i < lines.length) {
    let line = lines[i]

    // Skip empty lines
    if (!line.trim()) {
      i++
      continue
    }

    // Headings
    const hMatch = /^(#{1,6})\s+(.*)$/.exec(line)
    if (hMatch) {
      const level = hMatch[1].length
      const text = hMatch[2].trim()
      if (level === 1 && !leadingH1Skipped) {
        leadingH1Skipped = true
        i++
        continue
      }
      const HeadingTag = (`h${Math.min(6, Math.max(2, level))}` as unknown) as keyof JSX.IntrinsicElements
      const headingClass = level === 2
        ? 'text-2xl font-bold mt-10 mb-4'
        : level === 3
        ? 'text-xl font-semibold mt-8 mb-3'
        : 'text-lg font-semibold mt-6 mb-3'
      nodes.push(
        <HeadingTag key={`h-${nodes.length}`} className={headingClass}>
          {renderInline(text)}
        </HeadingTag>
      )
      i++
      continue
    }

    // Blockquote
    if (/^>\s?/.test(line)) {
      const qLines: string[] = []
      while (i < lines.length && /^>\s?/.test(lines[i])) {
        qLines.push(lines[i].replace(/^>\s?/, ''))
        i++
      }
      nodes.push(
        <blockquote key={`q-${nodes.length}`} className="border-l-4 pl-4 italic my-6">
          {renderInline(qLines.join(' '))}
        </blockquote>
      )
      continue
    }

    // Unordered list
    if (/^[-*]\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^[-*]\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^[-*]\s+/, ''))
        i++
      }
      nodes.push(
        <ul key={`ul-${nodes.length}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`uli-${nodes.length}-${idx}`} className="leading-relaxed">
              {renderInline(it)}
            </li>
          ))}
        </ul>
      )
      continue
    }

    // Ordered list
    if (/^\d+\.\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\d+\.\s+/, ''))
        i++
      }
      nodes.push(
        <ol key={`ol-${nodes.length}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${nodes.length}-${idx}`} className="leading-relaxed">
              {renderInline(it)}
            </li>
          ))}
        </ol>
      )
      continue
    }

    // Table
    if (isTableLine(line) && i + 1 < lines.length && isTableSepLine(lines[i + 1])) {
      const { tableNode, nextIndex } = parseTable(lines, i)
      nodes.push(tableNode)
      i = nextIndex
      continue
    }

    // Horizontal rule (avoid conflicting with table separator handled above)
    if (/^\s*---\s*$/.test(line)) {
      nodes.push(<hr key={`hr-${nodes.length}`} className="my-6 border-t" />)
      i++
      continue
    }

    // Paragraph: collect consecutive non-empty text lines until blank or block start
    const paraLines: string[] = []
    while (i < lines.length) {
      const l = lines[i]
      if (!l.trim()) break
      if (/^(#{1,6})\s+/.test(l)) break
      if (/^>\s?/.test(l)) break
      if (/^[-*]\s+/.test(l)) break
      if (/^\d+\.\s+/.test(l)) break
      if (isTableLine(l) && i + 1 < lines.length && isTableSepLine(lines[i + 1])) break
      paraLines.push(l)
      i++
    }
    pushParagraph(paraLines)
  }

  return nodes
}

function isTableLine(line: string): boolean {
  // A simple detection: line contains at least two pipe characters and some non-pipe content
  const trimmed = line.trim()
  if (!trimmed.includes('|')) return false
  const pipeCount = (trimmed.match(/\|/g) || []).length
  return pipeCount >= 2
}

function isTableSepLine(line: string): boolean {
  // e.g., | --- | --- | or --- | ---
  const segments = line.split('|').map(s => s.trim())
  if (segments.length < 2) return false
  // A separator row has only dashes/colons/spacing per cell
  const isSepCell = (s: string) => /^:?[-]+:?$/.test(s)
  const nonEmptyCells = segments.filter(s => s.length > 0)
  if (nonEmptyCells.length === 0) return false
  return nonEmptyCells.every(isSepCell)
}

function parseTable(lines: string[], start: number): { tableNode: React.ReactNode; nextIndex: number } {
  const rows: string[] = []
  let i = start
  while (i < lines.length && lines[i].trim() && isTableLine(lines[i])) {
    rows.push(lines[i])
    i++
  }
  // rows[0] header, rows[1] separator, others body
  const headerCells = splitTableRow(rows[0])
  const bodyRows = rows.slice(2).map(splitTableRow)

  const tableNode = (
    <table key={`tbl-${start}`} className="w-full border-collapse my-6">
      <thead>
        <tr>
          {headerCells.map((h, idx) => (
            <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold">
              {renderInline(h)}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {bodyRows.map((cells, rIdx) => (
          <tr key={`tr-${rIdx}`}>
            {cells.map((c, cIdx) => (
              <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left">
                {renderInline(c)}
              </td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  )

  return { tableNode, nextIndex: i }
}

function splitTableRow(row: string): string[] {
  // Remove leading/trailing pipes then split
  let r = row.trim()
  if (r.startsWith('|')) r = r.slice(1)
  if (r.endsWith('|')) r = r.slice(0, -1)
  return r.split('|').map(s => s.trim())
}

function renderInline(text: string): React.ReactNode[] {
  // First, handle inline code `code`
  const codeSplit = splitWithDelimiters(text, /`([^`]+)`/)
  const codeProcessed: Array<string | React.ReactNode> = []
  codeSplit.forEach((part, idx) => {
    if (typeof part === 'string') {
      codeProcessed.push(part)
    } else {
      // matched group captured in part.value
      codeProcessed.push(
        <code key={`code-${idx}`} className="bg-gray-100 rounded px-1 py-0.5 text-sm">
          {part.value}
        </code>
      )
    }
  })

  // Then links [text](url)
  const linkProcessed: Array<string | React.ReactNode> = []
  codeProcessed.forEach((segment, idx) => {
    if (typeof segment !== 'string') {
      linkProcessed.push(segment)
      return
    }
    const parts = splitWithDelimiters(segment, /\[([^\]]+)\]\(([^)]+)\)/)
    parts.forEach((p, pIdx) => {
      if (typeof p === 'string') {
        // auto-link plain URLs
        const urlParts = splitWithDelimiters(p, /(https?:\/\/[^\s)]+)/)
        urlParts.forEach((u, uIdx) => {
          if (typeof u === 'string') {
            linkProcessed.push(u)
          } else {
            linkProcessed.push(
              <a key={`auto-${idx}-${pIdx}-${uIdx}`} href={u.value} target="_blank" rel="noopener noreferrer" className="text-blue-600 underline hover:text-blue-800">
                {u.value}
              </a>
            )
          }
        })
      } else {
        const [label, url] = p.value.split('\u0000')
        linkProcessed.push(
          <a key={`link-${idx}-${pIdx}`} href={url} target="_blank" rel="noopener noreferrer" className="text-blue-600 underline hover:text-blue-800">
            {label}
          </a>
        )
      }
    })
  })

  // Bold **text** then italic *text*
  const boldProcessed: Array<string | React.ReactNode> = []
  linkProcessed.forEach((segment, idx) => {
    if (typeof segment !== 'string') {
      boldProcessed.push(segment)
      return
    }
    const parts = splitWithDelimiters(segment, /(\*\*|__)([^]*?)\1/)
    parts.forEach((p, pIdx) => {
      if (typeof p === 'string') {
        boldProcessed.push(p)
      } else {
        boldProcessed.push(
          <strong key={`b-${idx}-${pIdx}`} className="font-semibold">
            {p.value}
          </strong>
        )
      }
    })
  })

  const italicProcessed: Array<string | React.ReactNode> = []
  boldProcessed.forEach((segment, idx) => {
    if (typeof segment !== 'string') {
      italicProcessed.push(segment)
      return
    }
    const parts = splitWithDelimiters(segment, /(\*|_)([^]*?)\1/)
    parts.forEach((p, pIdx) => {
      if (typeof p === 'string') {
        italicProcessed.push(p)
      } else {
        italicProcessed.push(
          <em key={`i-${idx}-${pIdx}`} className="italic">
            {p.value}
          </em>
        )
      }
    })
  })

  return italicProcessed.map((n, i) => (typeof n === 'string' ? <React.Fragment key={`t-${i}`}>{n}</React.Fragment> : n))
}

// Utility to split string by regex while keeping matches with captured groups
// Returns array of strings and objects { value: string } where value is group content
function splitWithDelimiters(input: string, pattern: RegExp): Array<string | { value: string }> {
  const out: Array<string | { value: string }> = []
  let lastIndex = 0
  const regex = new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g')
  let match: RegExpExecArray | null
  while ((match = regex.exec(input)) !== null) {
    if (match.index > lastIndex) {
      out.push(input.slice(lastIndex, match.index))
    }
    if (match.length === 2) {
      out.push({ value: match[1] })
    } else if (match.length >= 3) {
      // For links, pack label and URL separated by NUL character to avoid collisions
      if (match.length === 3) {
        out.push({ value: `${match[1]}\u0000${match[2]}` })
      } else {
        out.push({ value: match[1] })
      }
    }
    lastIndex = regex.lastIndex
  }
  if (lastIndex < input.length) {
    out.push(input.slice(lastIndex))
  }
  return out
}


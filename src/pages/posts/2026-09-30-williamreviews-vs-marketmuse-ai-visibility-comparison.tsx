function stripLeadingH1(md: string): string {
  const lines = md.split('\n')
  if (lines.length === 0) return md
  if (/^#\s+/.test(lines[0].trim())) {
    // drop first line and a following blank line if present
    const rest = lines.slice(1)
    if (rest[0] !== undefined && rest[0].trim() === '') return rest.slice(1).join('\n')
    return rest.join('\n')
  }
  return md
}

function renderInline(text: string): React.ReactNode[] {
  const nodes: React.ReactNode[] = []
  const regex = /(\[([^\]]+)\]\(([^)]+)\))|(\*\*([^*]+)\*\*)|(\*([^*]+)\*)|(`([^`]+)`)/g
  let lastIndex = 0
  let match: RegExpExecArray | null
  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      nodes.push(text.slice(lastIndex, match.index))
    }
    if (match[1]) {
      // link
      const label = match[2]
      const href = match[3]
      nodes.push(
        <a key={nodes.length} href={href} className="text-blue-600 underline" target="_blank" rel="noopener noreferrer">
          {label}
        </a>
      )
    } else if (match[4]) {
      // bold
      nodes.push(
        <strong key={nodes.length} className="font-semibold">
          {match[5]}
        </strong>
      )
    } else if (match[6]) {
      // italic
      nodes.push(
        <em key={nodes.length} className="italic">
          {match[7]}
        </em>
      )
    } else if (match[8]) {
      // code
      nodes.push(
        <code key={nodes.length} className="font-mono text-sm bg-gray-100 px-1 py-0.5 rounded">
          {match[9]}
        </code>
      )
    }
    lastIndex = regex.lastIndex
  }
  if (lastIndex < text.length) {
    nodes.push(text.slice(lastIndex))
  }
  return nodes
}

function MarkdownRenderer({ content }: { content: string }) {
  const md = stripLeadingH1(content)
  const lines = md.split('\n')
  const elements: React.ReactNode[] = []

  let i = 0
  let key = 0

  function pushParagraph(paragraphLines: string[]) {
    const text = paragraphLines.join(' ').trim()
    if (text) {
      elements.push(
        <p key={`p-${key++}`} className="mb-4 leading-relaxed">
          {renderInline(text)}
        </p>
      )
    }
  }

  function isTableSeparatorRow(s: string) {
    const t = s.trim()
    return t.startsWith('|') && t.endsWith('|') && /\|\s*:?-{3,}:?\s*/.test(t)
  }

  while (i < lines.length) {
    const line = lines[i]
    const trimmed = line.trim()

    if (trimmed === '') {
      i++
      continue
    }

    // Table
    if (trimmed.startsWith('|') && trimmed.endsWith('|') && i + 1 < lines.length && isTableSeparatorRow(lines[i + 1])) {
      const headerCells = trimmed
        .slice(1, -1)
        .split('|')
        .map((c) => c.trim())
      i += 2 // skip header and separator
      const rows: string[][] = []
      while (i < lines.length && lines[i].trim().startsWith('|') && lines[i].trim().endsWith('|')) {
        const row = lines[i]
          .trim()
          .slice(1, -1)
          .split('|')
          .map((c) => c.trim())
        rows.push(row)
        i++
      }
      elements.push(
        <div key={`tbl-wrap-${key++}`} className="overflow-x-auto my-6">
          <table className="w-full border-collapse text-sm">
            <thead>
              <tr>
                {headerCells.map((h, idx) => (
                  <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                    {renderInline(h)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {rows.map((r, rIdx) => (
                <tr key={`tr-${rIdx}`} className="odd:bg-white even:bg-gray-50">
                  {r.map((c, cIdx) => (
                    <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 align-top">
                      {renderInline(c)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )
      continue
    }

    // Unordered list
    if (/^\s*-\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^\s*-\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*-\s+/, ''))
        i++
      }
      elements.push(
        <ul key={`ul-${key++}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`li-${idx}`}>{renderInline(it)}</li>
          ))}
        </ul>
      )
      continue
    }

    // Ordered list
    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*\d+\.\s+/, ''))
        i++
      }
      elements.push(
        <ol key={`ol-${key++}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`}>{renderInline(it)}</li>
          ))}
        </ol>
      )
      continue
    }

    // Blockquote
    if (trimmed.startsWith('>')) {
      const bqLines: string[] = []
      while (i < lines.length && lines[i].trim().startsWith('>')) {
        bqLines.push(lines[i].replace(/^\s*>\s?/, ''))
        i++
      }
      elements.push(
        <blockquote key={`bq-${key++}`} className="border-l-4 pl-4 italic my-6 text-gray-700">
          {renderInline(bqLines.join(' '))}
        </blockquote>
      )
      continue
    }

    // Headings
    if (/^###\s+/.test(trimmed)) {
      elements.push(
        <h3 key={`h3-${key++}`} className="text-xl font-semibold mt-8 mb-3">
          {renderInline(trimmed.replace(/^###\s+/, ''))}
        </h3>
      )
      i++
      continue
    }
    if (/^##\s+/.test(trimmed)) {
      elements.push(
        <h2 key={`h2-${key++}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(trimmed.replace(/^##\s+/, ''))}
        </h2>
      )
      i++
      continue
    }
    if (/^#\s+/.test(trimmed)) {
      // Map any additional H1 to section heading styling
      elements.push(
        <h2 key={`h2-alt-${key++}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(trimmed.replace(/^#\s+/, ''))}
        </h2>
      )
      i++
      continue
    }

    // Horizontal rule
    if (/^---+$/.test(trimmed)) {
      elements.push(<hr key={`hr-${key++}`} className="my-8 border-t" />)
      i++
      continue
    }

    // Paragraph
    const paraLines: string[] = [line]
    i++
    while (i < lines.length && lines[i].trim() !== '') {
      // stop early if next line begins a known block element
      const next = lines[i]
      if (
        /^\s*-\s+/.test(next) ||
        /^\s*\d+\.\s+/.test(next) ||
        next.trim().startsWith('|') ||
        next.trim().startsWith('>') ||
        /^#{1,6}\s+/.test(next.trim()) ||
        /^---+$/.test(next.trim())
      ) {
        break
      }
      paraLines.push(lines[i])
      i++
    }
    pushParagraph(paraLines)
  }

  return <div>{elements}</div>
}


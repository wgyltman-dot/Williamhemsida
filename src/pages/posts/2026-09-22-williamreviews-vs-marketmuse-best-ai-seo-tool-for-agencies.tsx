function inlineToHTML(text: string): string {
  // Escape HTML
  let html = text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

  // Links [text](url)
  html = html.replace(/\[(.+?)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" class="text-blue-600 underline hover:text-blue-700" target="_blank" rel="noopener noreferrer">$1<\/a>');
  // Bold **text**
  html = html.replace(/\*\*(.+?)\*\*/g, '<strong class="font-semibold">$1<\/strong>');
  // Italic *text*
  html = html.replace(/(^|[^*])\*(?!\s)([^*]+?)\*(?!\*)/g, '$1<em class="italic">$2<\/em>');
  // Inline code `code`
  html = html.replace(/`([^`]+?)`/g, '<code class="bg-gray-100 rounded px-1 py-0.5 text-sm">$1<\/code>');

  return html;
}

function MarkdownRenderer({ content }: { content: string }) {
  const lines = content.split(/\r?\n/);
  let i = 0;
  const out: React.ReactNode[] = [];
  let key = 0;

  // Skip leading H1
  if (lines[i] && /^#\s+/.test(lines[i])) {
    i += 1;
    if (lines[i] !== undefined && lines[i].trim() === "") i += 1;
  }

  const nextKey = () => `${key++}`;

  const renderParagraph = (text: string) => (
    <p
      key={nextKey()}
      className="mb-4 leading-relaxed text-gray-800"
      dangerouslySetInnerHTML={{ __html: inlineToHTML(text) }}
    />
  );

  const parseTable = (tableLines: string[]) => {
    if (tableLines.length < 2) return null;
    const splitRow = (row: string) =>
      row
        .trim()
        .replace(/^\|/, "")
        .replace(/\|$/, "")
        .split("|")
        .map((c) => c.trim());

    const header = splitRow(tableLines[0]);
    // tableLines[1] is separator like | --- | --- |
    const rows = tableLines.slice(2).map(splitRow);

    return (
      <div key={nextKey()} className="my-6 overflow-x-auto">
        <table className="w-full border-collapse">
          <thead>
            <tr>
              {header.map((h, idx) => (
                <th
                  key={idx}
                  className="border px-3 py-2 text-left bg-gray-50 text-gray-900 font-semibold"
                  dangerouslySetInnerHTML={{ __html: inlineToHTML(h) }}
                />
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((r, rIdx) => (
              <tr key={rIdx} className="odd:bg-white even:bg-gray-50">
                {r.map((c, cIdx) => (
                  <td
                    key={cIdx}
                    className="border px-3 py-2 align-top text-gray-800"
                    dangerouslySetInnerHTML={{ __html: inlineToHTML(c) }}
                  />
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );
  };

  while (i < lines.length) {
    const line = lines[i] ?? "";
    const trimmed = line.trim();

    // Skip extra blank lines
    if (trimmed === "") {
      i += 1;
      continue;
    }

    // Headings
    if (/^###\s+/.test(trimmed)) {
      const text = trimmed.replace(/^###\s+/, "");
      out.push(
        <h3 key={nextKey()} className="text-xl font-semibold mt-8 mb-3 text-gray-900">
          <span dangerouslySetInnerHTML={{ __html: inlineToHTML(text) }} />
        </h3>
      );
      i += 1;
      continue;
    }

    if (/^##\s+/.test(trimmed)) {
      const text = trimmed.replace(/^##\s+/, "");
      out.push(
        <h2 key={nextKey()} className="text-2xl font-bold mt-10 mb-4 text-gray-900">
          <span dangerouslySetInnerHTML={{ __html: inlineToHTML(text) }} />
        </h2>
      );
      i += 1;
      continue;
    }

    // Blockquote
    if (/^>\s?/.test(trimmed)) {
      const bq: string[] = [];
      while (i < lines.length && /^>\s?/.test(lines[i]!.trim())) {
        bq.push(lines[i]!.trim().replace(/^>\s?/, ""));
        i += 1;
      }
      out.push(
        <blockquote key={nextKey()} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-700">
          {renderParagraph(bq.join(" "))}
        </blockquote>
      );
      continue;
    }

    // Table block: lines starting with |
    if (/^\|/.test(trimmed)) {
      const tLines: string[] = [];
      while (i < lines.length && /^\|/.test(lines[i]!.trim())) {
        tLines.push(lines[i]!);
        i += 1;
      }
      const tableEl = parseTable(tLines);
      if (tableEl) out.push(tableEl);
      continue;
    }

    // Unordered list
    if (/^[-]\s+/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^[-]\s+/.test(lines[i]!.trim())) {
        items.push(lines[i]!.trim().replace(/^[-]\s+/, ""));
        i += 1;
      }
      out.push(
        <ul key={nextKey()} className="list-disc pl-6 mb-4 space-y-2 text-gray-800">
          {items.map((it, idx) => (
            <li key={idx} dangerouslySetInnerHTML={{ __html: inlineToHTML(it) }} />
          ))}
        </ul>
      );
      continue;
    }

    // Ordered list
    if (/^\d+\.\s+/.test(trimmed)) {
      const items: string[] = [];
      while (i < lines.length && /^\d+\.\s+/.test(lines[i]!.trim())) {
        items.push(lines[i]!.trim().replace(/^\d+\.\s+/, ""));
        i += 1;
      }
      out.push(
        <ol key={nextKey()} className="list-decimal pl-6 mb-4 space-y-2 text-gray-800">
          {items.map((it, idx) => (
            <li key={idx} dangerouslySetInnerHTML={{ __html: inlineToHTML(it) }} />
          ))}
        </ol>
      );
      continue;
    }

    // Horizontal rule (only when line is exactly ---)
    if (/^---$/.test(trimmed)) {
      out.push(<hr key={nextKey()} className="my-6 border-gray-300" />);
      i += 1;
      continue;
    }

    // Paragraph (collect until blank line or next block)
    const para: string[] = [trimmed];
    i += 1;
    while (
      i < lines.length &&
      lines[i]!.trim() !== "" &&
      !/^(#{2,3})\s+/.test(lines[i]!.trim()) &&
      !/^[-]\s+/.test(lines[i]!.trim()) &&
      !/^\d+\.\s+/.test(lines[i]!.trim()) &&
      !/^\|/.test(lines[i]!.trim()) &&
      !/^>\s?/.test(lines[i]!.trim()) &&
      !/^---$/.test(lines[i]!.trim())
    ) {
      para.push(lines[i]!.trim());
      i += 1;
    }
    out.push(renderParagraph(para.join(" ")));
  }

  return <div>{out}</div>;
}


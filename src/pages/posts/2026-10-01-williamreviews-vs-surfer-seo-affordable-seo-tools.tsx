function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

function renderInline(text: string): React.ReactNode {
  let html = escapeHtml(text)
  // code
  html = html.replace(/`([^`]+)`/g, '<code class="px-1 py-0.5 rounded bg-gray-100 text-gray-800">$1<\/code>')
  // bold
  html = html.replace(/\*\*([^*]+)\*\*/g, '<strong>$1<\/strong>')
  // italic
  html = html.replace(/(^|[^*])\*([^*]+)\*(?!\*)/g, '$1<em>$2<\/em>')
  // links [text](url)
  html = html.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" class="underline text-blue-600 hover:text-blue-700">$1<\/a>')
  return <span dangerouslySetInnerHTML={{ __html: html }} />
}

function MarkdownRenderer({ content }: { content: string }) {
  const lines = content.split('\n')

  // skip leading H1 to avoid duplicate title
  let i = 0
  if (lines[i] && lines[i].startsWith('# ')) {
    i++
    while (i < lines.length && lines[i].trim() === '') i++
  }

  const elements: React.ReactNode[] = []
  let key = 0

  const pushParagraph = (buffer: string[]) => {
    if (buffer.length === 0) return
    const text = buffer.join(' ').trim()
    if (text) {
      elements.push(
        <p key={key++} className="mb-4 leading-relaxed text-gray-800">
          {renderInline(text)}
        </p>
      )
    }
  }

  while (i < lines.length) {
    const line = lines[i]

    // horizontal rule
    if (/^\s*-{3,}\s*$/.test(line)) {
      elements.push(<hr key={key++} className="my-8 border-t border-gray-200" />)
      i++
      continue
    }

    // headings ## to ######
    const headingMatch = line.match(/^(#{2,6})\s+(.*)$/)
    if (headingMatch) {
      const level = headingMatch[1].length
      const text = headingMatch[2]
      if (level === 2) {
        elements.push(
          <h2 key={key++} className="text-2xl font-bold mt-10 mb-4 text-gray-900">
            {renderInline(text)}
          </h2>
        )
      } else if (level === 3) {
        elements.push(
          <h3 key={key++} className="text-xl font-semibold mt-8 mb-3 text-gray-900">
            {renderInline(text)}
          </h3>
        )
      } else if (level === 4) {
        elements.push(
          <h4 key={key++} className="text-lg font-semibold mt-6 mb-2 text-gray-900">
            {renderInline(text)}
          </h4>
        )
      } else {
        elements.push(
          <h5 key={key++} className="text-base font-semibold mt-6 mb-2 text-gray-900">
            {renderInline(text)}
          </h5>
        )
      }
      i++
      continue
    }

    // blockquote
    if (line.startsWith('> ')) {
      const bqLines: string[] = []
      while (i < lines.length && lines[i].startsWith('> ')) {
        bqLines.push(lines[i].replace(/^>\s?/, ''))
        i++
      }
      elements.push(
        <blockquote key={key++} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-700">
          {renderInline(bqLines.join(' '))}
        </blockquote>
      )
      continue
    }

    // table
    if (line.trim().startsWith('|')) {
      const next = lines[i + 1] || ''
      if (next.includes('---')) {
        const headerRow = line
        const separatorRow = next
        const rows: string[] = []
        i += 2
        while (i < lines.length && lines[i].trim().startsWith('|') && !/^\s*$/.test(lines[i])) {
          rows.push(lines[i])
          i++
        }
        const parseCells = (row: string) =>
          row
            .trim()
            .replace(/^\||\|$/g, '')
            .split('|')
            .map((c) => c.trim())

        const headers = parseCells(headerRow)
        const bodyRows = rows.map(parseCells)

        elements.push(
          <div key={key++} className="my-6 overflow-x-auto">
            <table className="w-full border-collapse">
              <thead>
                <tr>
                  {headers.map((h, idx) => (
                    <th key={idx} className="border px-3 py-2 text-left bg-gray-50 text-gray-900 font-semibold">
                      {renderInline(h)}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {bodyRows.map((r, rIdx) => (
                  <tr key={rIdx} className="odd:bg-white even:bg-gray-50">
                    {r.map((cell, cIdx) => (
                      <td key={cIdx} className="border px-3 py-2 text-gray-800 align-top">
                        {renderInline(cell)}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )
        continue
      }
    }

    // unordered list
    if (/^\s*[-*]\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^\s*[-*]\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*[-*]\s+/, ''))
        i++
      }
      elements.push(
        <ul key={key++} className="list-disc pl-6 mb-4 space-y-2 text-gray-800">
          {items.map((it, idx) => (
            <li key={idx}>{renderInline(it)}</li>
          ))}
        </ul>
      )
      continue
    }

    // ordered list
    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = []
      while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*\d+\.\s+/, ''))
        i++
      }
      elements.push(
        <ol key={key++} className="list-decimal pl-6 mb-4 space-y-2 text-gray-800">
          {items.map((it, idx) => (
            <li key={idx}>{renderInline(it)}</li>
          ))}
        </ol>
      )
      continue
    }

    // paragraph or blank
    if (line.trim() === '') {
      // skip extra blank lines
      i++
      continue
    } else {
      const buffer: string[] = []
      while (i < lines.length && lines[i].trim() !== '') {
        buffer.push(lines[i])
        i++
      }
      pushParagraph(buffer)
      continue
    }
  }

  return <div>{elements}</div>
}


function MarkdownRenderer({ content }: { content: string }): React.ReactElement {
  const elements: React.ReactNode[] = []

  const lines = content.split(/\r?\n/)
  let i = 0
  let firstContentSeen = false
  let firstH1Skipped = false

  function renderInline(text: string): React.ReactNode[] {
    // Process links first: [text](url)
    const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g
    const nodes: React.ReactNode[] = []
    let lastIndex = 0
    let match: RegExpExecArray | null
    while ((match = linkRegex.exec(text)) !== null) {
      if (match.index > lastIndex) {
        nodes.push(...renderInlineNoLinks(text.slice(lastIndex, match.index)))
      }
      const label = match[1]
      const href = match[2]
      nodes.push(
        <a key={`a-${nodes.length}`} href={href} className="text-blue-600 underline hover:text-blue-800" rel="noopener noreferrer">
          {renderInlineNoLinks(label)}
        </a>
      )
      lastIndex = match.index + match[0].length
    }
    if (lastIndex < text.length) {
      nodes.push(...renderInlineNoLinks(text.slice(lastIndex)))
    }
    return nodes
  }

  function renderInlineNoLinks(text: string): React.ReactNode[] {
    // Handle code segments by splitting on backticks
    const parts = text.split('`')
    const nodes: React.ReactNode[] = []
    for (let idx = 0; idx < parts.length; idx++) {
      const segment = parts[idx]
      const isCode = idx % 2 === 1
      if (isCode) {
        nodes.push(
          <code key={`code-${nodes.length}`} className="bg-gray-100 rounded px-1 py-0.5 text-sm">
            {segment}
          </code>
        )
      } else {
        // Handle bold (**)
        const boldParts = segment.split('**')
        for (let b = 0; b < boldParts.length; b++) {
          const boldSeg = boldParts[b]
          const isBold = b % 2 === 1
          if (isBold) {
            nodes.push(
              <strong key={`strong-${nodes.length}`} className="font-semibold">
                {renderItalics(boldSeg)}
              </strong>
            )
          } else {
            nodes.push(...renderItalics(boldSeg))
          }
        }
      }
    }
    return nodes
  }

  function renderItalics(text: string): React.ReactNode[] {
    const italicsParts = text.split('*')
    const res: React.ReactNode[] = []
    for (let j = 0; j < italicsParts.length; j++) {
      const seg = italicsParts[j]
      const isEm = j % 2 === 1
      if (isEm) {
        res.push(
          <em key={`em-${res.length}`} className="italic">
            {seg}
          </em>
        )
      } else {
        if (seg) res.push(seg)
      }
    }
    return res
  }

  function isTableLine(line: string): boolean {
    return /\|/.test(line)
  }

  function parseTable(startIndex: number): number {
    const tableLines: string[] = []
    let idx = startIndex
    while (idx < lines.length && isTableLine(lines[idx])) {
      tableLines.push(lines[idx])
      idx++
    }
    // Determine header by presence of a separator like --- | ---
    let headerCells: string[] | null = null
    const rows: string[][] = []
    if (tableLines.length > 0) {
      const first = tableLines[0]
      const second = tableLines[1] || ''
      const isSeparator = /^\s*[:\-\|\s]+$/.test(second)
      const splitRow = (row: string): string[] =>
        row
          .split('|')
          .map((c) => c.trim())
          .filter((c, idx2, arr) => !(idx2 === 0 && c === '') && !(idx2 === arr.length - 1 && c === ''))
      if (isSeparator) {
        headerCells = splitRow(first)
        for (let r = 2; r < tableLines.length; r++) {
          rows.push(splitRow(tableLines[r]))
        }
      } else {
        rows.push(splitRow(first))
        for (let r = 1; r < tableLines.length; r++) {
          rows.push(splitRow(tableLines[r]))
        }
      }
    }

    elements.push(
      <div key={`table-${elements.length}`} className="overflow-auto">
        <table className="w-full border-collapse my-6 text-sm">
          {headerCells && (
            <thead>
              <tr>
                {headerCells.map((h, hi) => (
                  <th key={`th-${hi}`} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
          )}
          <tbody>
            {rows.map((r, ri) => (
              <tr key={`tr-${ri}`}>
                {r.map((c, ci) => (
                  <td key={`td-${ri}-${ci}`} className="border px-3 py-2">
                    {renderInline(c)}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    )

    return idx
  }

  function parseList(start: number, ordered: boolean): number {
    const items: string[] = []
    let idx = start
    const ulRegex = /^\s*[-*]\s+(.+)/
    const olRegex = /^\s*\d+\.\s+(.+)/
    while (idx < lines.length) {
      const line = lines[idx]
      const match = ordered ? olRegex.exec(line) : ulRegex.exec(line)
      if (match) {
        items.push(match[1])
        idx++
      } else if (line.trim() === '') {
        idx++
        break
      } else {
        break
      }
    }
    if (ordered) {
      elements.push(
        <ol key={`ol-${elements.length}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, li) => (
            <li key={`oli-${li}`}>{renderInline(it)}</li>
          ))}
        </ol>
      )
    } else {
      elements.push(
        <ul key={`ul-${elements.length}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, li) => (
            <li key={`uli-${li}`}>{renderInline(it)}</li>
          ))}
        </ul>
      )
    }
    return idx
  }

  function parseBlockquote(start: number): number {
    const bqLines: string[] = []
    let idx = start
    while (idx < lines.length) {
      const line = lines[idx]
      if (/^>\s?/.test(line)) {
        bqLines.push(line.replace(/^>\s?/, ''))
        idx++
      } else if (line.trim() === '') {
        // allow a blank within blockquote to separate paragraphs
        bqLines.push('')
        idx++
      } else {
        break
      }
    }
    const text = bqLines.join('\n')
    elements.push(
      <blockquote key={`bq-${elements.length}`} className="border-l-4 pl-4 italic my-6 text-gray-700">
        {renderParagraphs(text)}
      </blockquote>
    )
    return idx
  }

  function renderParagraphs(text: string): React.ReactNode {
    const paras = text.split(/\n{2,}/)
    return (
      <>
        {paras.map((p, idx) => (
          <p key={`p-bq-${idx}`} className="mb-4 leading-relaxed">
            {renderInline(p.replace(/\n/g, ' '))}
          </p>
        ))}
      </>
    )
  }

  function parseParagraph(start: number): number {
    const buf: string[] = []
    let idx = start
    while (idx < lines.length) {
      const line = lines[idx]
      if (line.trim() === '') {
        idx++
        break
      }
      // Stop if next is a block element
      if (/^\s*[-*]\s+/.test(line) || /^\s*\d+\.\s+/.test(line) || /^>\s?/.test(line) || /^#{1,6}\s+/.test(line) || isTableLine(line) || /^\s*---\s*$/.test(line)) {
        break
      }
      buf.push(line)
      idx++
    }
    const text = buf.join(' ')
    elements.push(
      <p key={`p-${elements.length}`} className="mb-4 leading-relaxed">
        {renderInline(text)}
      </p>
    )
    return idx
  }

  while (i < lines.length) {
    let line = lines[i]

    // Track first non-empty content to decide H1 skip
    if (!firstContentSeen && line.trim() !== '') {
      firstContentSeen = true
      if (/^#\s+/.test(line) && !firstH1Skipped) {
        // skip leading H1
        firstH1Skipped = true
        i++
        continue
      }
    }

    // Horizontal rule
    if (/^\s*---\s*$/.test(line)) {
      elements.push(<hr key={`hr-${elements.length}`} className="my-8 border-t" />)
      i++
      continue
    }

    // Headings h2-h6
    const hMatch = /^(#{2,6})\s+(.+)/.exec(line)
    if (hMatch) {
      const level = hMatch[1].length
      const text = hMatch[2]
      const common = 'mt-8 mb-3'
      if (level === 2) {
        elements.push(
          <h2 key={`h2-${elements.length}`} className={`text-2xl font-bold mt-10 mb-4`}>
            {renderInline(text)}
          </h2>
        )
      } else if (level === 3) {
        elements.push(
          <h3 key={`h3-${elements.length}`} className={`text-xl font-semibold ${common}`}>
            {renderInline(text)}
          </h3>
        )
      } else if (level === 4) {
        elements.push(
          <h4 key={`h4-${elements.length}`} className={`text-lg font-semibold ${common}`}>
            {renderInline(text)}
          </h4>
        )
      } else if (level === 5) {
        elements.push(
          <h5 key={`h5-${elements.length}`} className={`text-base font-semibold ${common}`}>
            {renderInline(text)}
          </h5>
        )
      } else {
        elements.push(
          <h6 key={`h6-${elements.length}`} className={`text-sm font-semibold ${common}`}>
            {renderInline(text)}
          </h6>
        )
      }
      i++
      continue
    }

    // Blockquote
    if (/^>\s?/.test(line)) {
      i = parseBlockquote(i)
      continue
    }

    // Tables
    if (isTableLine(line)) {
      i = parseTable(i)
      continue
    }

    // Lists
    if (/^\s*[-*]\s+/.test(line)) {
      i = parseList(i, false)
      continue
    }
    if (/^\s*\d+\.\s+/.test(line)) {
      i = parseList(i, true)
      continue
    }

    if (line.trim() === '') {
      i++
      continue
    }

    // Paragraph
    i = parseParagraph(i)
  }

  return <div>{elements}</div>
}

function formatDate(iso: string): string {
  try {
    const d = new Date(iso)
    return d.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' })
  } catch {
    return iso
  }
}


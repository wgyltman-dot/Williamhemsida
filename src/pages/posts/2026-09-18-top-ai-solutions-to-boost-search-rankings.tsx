function MarkdownRenderer({ content }: { content: string }) {
  const lines = content.split(/\r?\n/);
  const elements: React.ReactNode[] = [];
  let i = 0;
  let skippedFirstH1 = false;

  const renderInline = (text: string): React.ReactNode[] => {
    const parts: React.ReactNode[] = [];
    const regex = /(\*\*[^*]+\*\*|`[^`]+`|\*[^*]+\*|\[[^\]]+\]\([^\)]+\))/g;
    let lastIndex = 0;
    let match: RegExpExecArray | null;
    while ((match = regex.exec(text)) !== null) {
      if (match.index > lastIndex) {
        parts.push(text.slice(lastIndex, match.index));
      }
      const token = match[0];
      if (token.startsWith("**") && token.endsWith("**")) {
        parts.push(<strong key={parts.length}>{token.slice(2, -2)}</strong>);
      } else if (token.startsWith("*") && token.endsWith("*")) {
        parts.push(<em key={parts.length}>{token.slice(1, -1)}</em>);
      } else if (token.startsWith("`") && token.endsWith("`")) {
        parts.push(
          <code key={parts.length} className="px-1 py-0.5 bg-gray-100 rounded text-sm">
            {token.slice(1, -1)}
          </code>
        );
      } else if (token.startsWith("[")) {
        const m = token.match(/^\[([^\]]+)\]\(([^\)]+)\)$/);
        if (m) {
          parts.push(
            <a key={parts.length} href={m[2]} className="text-blue-600 underline" rel="noopener noreferrer" target="_blank">
              {m[1]}
            </a>
          );
        } else {
          parts.push(token);
        }
      } else {
        parts.push(token);
      }
      lastIndex = regex.lastIndex;
    }
    if (lastIndex < text.length) {
      parts.push(text.slice(lastIndex));
    }
    return parts;
  };

  const parseTable = () => {
    const headerLine = lines[i];
    const separatorLine = lines[i + 1] ?? "";
    const isSeparator = /^\s*\|?\s*:?[-]+:?\s*(\|\s*:?[-]+:?\s*)+\|?\s*$/.test(separatorLine);
    if (!headerLine.includes("|") || !isSeparator) return null;

    const toCells = (line: string) =>
      line
        .trim()
        .replace(/^\|/, "")
        .replace(/\|$/, "")
        .split("|")
        .map((c) => c.trim());

    const headers = toCells(headerLine);
    i += 2; // skip header and separator
    const rows: string[][] = [];
    while (i < lines.length && lines[i].includes("|") && lines[i].trim() !== "") {
      rows.push(toCells(lines[i]));
      i++;
    }

    return (
      <table key={elements.length} className="w-full border-collapse my-6">
        <thead>
          <tr>
            {headers.map((h, idx) => (
              <th key={idx} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                {renderInline(h)}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, rIdx) => (
            <tr key={rIdx}>
              {row.map((c, cIdx) => (
                <td key={cIdx} className="border px-3 py-2 text-left align-top">{renderInline(c)}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    );
  };

  while (i < lines.length) {
    const line = lines[i];

    // Blank line
    if (!line || line.trim() === "") {
      i++;
      continue;
    }

    // Horizontal rule
    if (/^\s*---+\s*$/.test(line)) {
      elements.push(<hr key={elements.length} className="my-8 border-gray-200" />);
      i++;
      continue;
    }

    // Table
    const tableEl = parseTable();
    if (tableEl) {
      elements.push(tableEl);
      continue;
    }

    // Blockquote
    if (/^>\s+/.test(line)) {
      const bqLines: string[] = [];
      while (i < lines.length && /^>\s+/.test(lines[i])) {
        bqLines.push(lines[i].replace(/^>\s+/, ""));
        i++;
      }
      elements.push(
        <blockquote key={elements.length} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-700">
          {renderInline(bqLines.join(" "))}
        </blockquote>
      );
      continue;
    }

    // Unordered list
    if (/^[-*+]\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^[-*+]\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^[-*+]\s+/, ""));
        i++;
      }
      elements.push(
        <ul key={elements.length} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={idx}>{renderInline(it)}</li>
          ))}
        </ul>
      );
      continue;
    }

    // Ordered list
    if (/^\d+\.\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\d+\.\s+/, ""));
        i++;
      }
      elements.push(
        <ol key={elements.length} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={idx}>{renderInline(it)}</li>
          ))}
        </ol>
      );
      continue;
    }

    // Headings
    if (/^#{1,6}\s+/.test(line)) {
      const level = (line.match(/^#+/)?.[0].length || 1);
      const text = line.replace(/^#{1,6}\s+/, "");
      if (level === 1 && !skippedFirstH1) {
        skippedFirstH1 = true;
        i++;
        continue;
      }
      if (level === 2) {
        elements.push(
          <h2 key={elements.length} className="text-2xl font-bold mt-10 mb-4">{renderInline(text)}</h2>
        );
      } else if (level === 3) {
        elements.push(
          <h3 key={elements.length} className="text-xl font-semibold mt-8 mb-3">{renderInline(text)}</h3>
        );
      } else if (level === 4) {
        elements.push(
          <h4 key={elements.length} className="text-lg font-semibold mt-6 mb-2">{renderInline(text)}</h4>
        );
      } else {
        elements.push(
          <h5 key={elements.length} className="text-base font-semibold mt-6 mb-2">{renderInline(text)}</h5>
        );
      }
      i++;
      continue;
    }

    // Paragraph (collect consecutive non-empty lines that are not other blocks)
    const paraLines: string[] = [];
    while (
      i < lines.length &&
      lines[i].trim() !== "" &&
      !/^\s*---+\s*$/.test(lines[i]) &&
      !/^>\s+/.test(lines[i]) &&
      !/^\d+\.\s+/.test(lines[i]) &&
      !/^[-*+]\s+/.test(lines[i]) &&
      !/^#{1,6}\s+/.test(lines[i])
    ) {
      paraLines.push(lines[i]);
      i++;
    }
    const paraText = paraLines.join(" ").trim();
    if (paraText) {
      elements.push(
        <p key={elements.length} className="mb-4 leading-relaxed text-gray-800">
          {renderInline(paraText)}
        </p>
      );
    }
  }

  return <div>{elements}</div>;
}


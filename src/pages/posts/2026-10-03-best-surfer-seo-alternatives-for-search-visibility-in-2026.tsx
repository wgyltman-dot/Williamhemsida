function MarkdownRenderer({ content }: { content: string }) {
  // Skip leading H1 if present and render markdown blocks
  const elements: React.ReactNode[] = []

  const renderInline = (text: string, keyPrefix: string) => {
    let segments: Array<string | React.ReactNode> = [text]

    const splitByRegex = (
      input: Array<string | React.ReactNode>,
      regex: RegExp,
      render: (match: RegExpExecArray, i: number) => React.ReactNode
    ) => {
      const output: Array<string | React.ReactNode> = []
      input.forEach((seg) => {
        if (typeof seg !== 'string') {
          output.push(seg)
          return
        }
        let lastIndex = 0
        let match: RegExpExecArray | null
        let localIndex = 0
        while ((match = regex.exec(seg)) !== null) {
          if (match.index > lastIndex) {
            output.push(seg.slice(lastIndex, match.index))
          }
          output.push(render(match, localIndex++))
          lastIndex = match.index + match[0].length
        }
        if (lastIndex < seg.length) {
          output.push(seg.slice(lastIndex))
        }
        regex.lastIndex = 0
      })
      return output
    }

    // Inline code
    segments = splitByRegex(segments, /`([^`]+)`/g, (m, i) => (
      <code key={`${keyPrefix}-code-${i}`} className="bg-gray-100 px-1 rounded text-sm">
        {m[1]}
      </code>
    ))

    // Markdown links [text](url)
    segments = splitByRegex(segments, /\[([^\]]+)\]\(([^)]+)\)/g, (m, i) => (
      <a
        key={`${keyPrefix}-link-${i}`}
        href={m[2]}
        target="_blank"
        rel="noopener noreferrer"
        className="text-blue-600 underline"
      >
        {m[1]}
      </a>
    ))

    // Raw URLs
    segments = splitByRegex(segments, /(https?:\/\/[^\s)]+)(?![^<]*>)/g, (m, i) => (
      <a
        key={`${keyPrefix}-raw-${i}`}
        href={m[1]}
        target="_blank"
        rel="noopener noreferrer"
        className="text-blue-600 underline break-all"
      >
        {m[1]}
      </a>
    ))

    // Bold
    segments = splitByRegex(segments, /\*\*([^*]+)\*\*/g, (m, i) => (
      <strong key={`${keyPrefix}-b-${i}`} className="font-semibold">{m[1]}</strong>
    ))

    // Italic (single asterisks)
    segments = splitByRegex(segments, /\*([^*]+)\*/g, (m, i) => (
      <em key={`${keyPrefix}-i-${i}`} className="italic">{m[1]}</em>
    ))

    return segments
  }

  const toElements = (md: string) => {
    const lines = md.replace(/\r\n?/g, '\n').split('\n')

    // Remove leading H1 if it's the first non-empty line
    let ptr = 0
    while (ptr < lines.length && lines[ptr].trim() === '') ptr++
    if (ptr < lines.length && /^#\s+/.test(lines[ptr])) {
      lines.splice(ptr, 1)
    }

    let i = 0
    let key = 0
    let paragraph: string[] = []

    const flushParagraph = () => {
      if (paragraph.length) {
        const text = paragraph.join(' ').trim()
        if (text) {
          elements.push(
            <p key={`p-${key++}`} className="mb-4 leading-relaxed">
              {renderInline(text, `p-${key}`)}
            </p>
          )
        }
        paragraph = []
      }
    }

    const parseTable = () => {
      const start = i
      const header = lines[i]
      const sep = lines[i + 1] || ''
      if (!/\|/.test(header) || !/\|?\s*:?-{3,}.*\|?/.test(sep)) return false
      const rows: string[] = []
      i += 2
      while (i < lines.length && /\|/.test(lines[i]) && lines[i].trim() !== '') {
        rows.push(lines[i])
        i++
      }
      const headers = header
        .split('|')
        .map((c) => c.trim())
        .filter((c) => c.length)
      const data = rows.map((r) =>
        r
          .split('|')
          .map((c) => c.trim())
          .filter((c) => c.length)
      )
      elements.push(
        <div key={`tbl-${key++}`} className="overflow-x-auto my-6">
          <table className="w-full border-collapse">
            <thead>
              <tr>
                {headers.map((h, idx) => (
                  <th key={`th-${idx}`} className="border px-3 py-2 text-left bg-gray-50">
                    {renderInline(h, `th-${idx}`)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {data.map((row, rIdx) => (
                <tr key={`tr-${rIdx}`} className="odd:bg-white even:bg-gray-50">
                  {row.map((cell, cIdx) => (
                    <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left align-top">
                      {renderInline(cell, `td-${rIdx}-${cIdx}`)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )
      return true
    }

    while (i < lines.length) {
      const line = lines[i]

      // Horizontal rule
      if (/^\s*---\s*$/.test(line)) {
        flushParagraph()
        elements.push(<hr key={`hr-${key++}`} className="my-8 border-t" />)
        i++
        continue
      }

      // Tables
      if (parseTable()) {
        continue
      }

      // Headings
      const hMatch = /^(#{2,6})\s+(.*)$/.exec(line)
      if (hMatch) {
        flushParagraph()
        const level = hMatch[1].length
        const text = hMatch[2].trim()
        if (level === 2) {
          elements.push(
            <h2 key={`h2-${key++}`} className="text-2xl font-bold mt-10 mb-4">
              {renderInline(text, `h2-${key}`)}
            </h2>
          )
        } else if (level === 3) {
          elements.push(
            <h3 key={`h3-${key++}`} className="text-xl font-semibold mt-8 mb-3">
              {renderInline(text, `h3-${key}`)}
            </h3>
          )
        } else if (level === 4) {
          elements.push(
            <h4 key={`h4-${key++}`} className="text-lg font-semibold mt-6 mb-3">
              {renderInline(text, `h4-${key}`)}
            </h4>
          )
        } else if (level === 5) {
          elements.push(
            <h5 key={`h5-${key++}`} className="text-base font-semibold mt-6 mb-2">
              {renderInline(text, `h5-${key}`)}
            </h5>
          )
        } else {
          elements.push(
            <h6 key={`h6-${key++}`} className="text-sm font-semibold mt-4 mb-2 uppercase tracking-wide">
              {renderInline(text, `h6-${key}`)}
            </h6>
          )
        }
        i++
        continue
      }

      // Blockquote
      if (/^>\s?/.test(line)) {
        flushParagraph()
        const qLines: string[] = []
        while (i < lines.length && /^>\s?/.test(lines[i])) {
          qLines.push(lines[i].replace(/^>\s?/, ''))
          i++
        }
        const qText = qLines.join(' ').trim()
        elements.push(
          <blockquote key={`q-${key++}`} className="border-l-4 pl-4 italic my-6">
            {renderInline(qText, `q-${key}`)}
          </blockquote>
        )
        continue
      }

      // Unordered list
      if (/^\s*[-*]\s+/.test(line)) {
        flushParagraph()
        const items: string[] = []
        while (i < lines.length && /^\s*[-*]\s+/.test(lines[i])) {
          items.push(lines[i].replace(/^\s*[-*]\s+/, ''))
          i++
        }
        elements.push(
          <ul key={`ul-${key++}`} className="list-disc pl-6 mb-4 space-y-2">
            {items.map((it, idx) => (
              <li key={`li-${idx}`}>{renderInline(it, `ul-${key}-li-${idx}`)}</li>
            ))}
          </ul>
        )
        continue
      }

      // Ordered list
      if (/^\s*\d+\.\s+/.test(line)) {
        flushParagraph()
        const items: string[] = []
        while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
          items.push(lines[i].replace(/^\s*\d+\.\s+/, ''))
          i++
        }
        elements.push(
          <ol key={`ol-${key++}`} className="list-decimal pl-6 mb-4 space-y-2">
            {items.map((it, idx) => (
              <li key={`oli-${idx}`}>{renderInline(it, `ol-${key}-li-${idx}`)}</li>
            ))}
          </ol>
        )
        continue
      }

      // Code block (fenced)
      if (/^```/.test(line)) {
        flushParagraph()
        i++
        const codeLines: string[] = []
        while (i < lines.length && !/^```/.test(lines[i])) {
          codeLines.push(lines[i])
          i++
        }
        // skip closing ```
        if (i < lines.length && /^```/.test(lines[i])) i++
        elements.push(
          <pre key={`pre-${key++}`} className="bg-gray-900 text-gray-100 text-sm rounded p-4 overflow-x-auto my-4">
            <code>{codeLines.join('\n')}</code>
          </pre>
        )
        continue
      }

      // Blank line -> paragraph break
      if (line.trim() === '') {
        flushParagraph()
        i++
        continue
      }

      // Accumulate paragraph text
      paragraph.push(line.trim())
      i++
    }

    flushParagraph()
  }

  toElements(content)
  return <div>{elements}</div>
}

export default function PostPage() {
  const published = new Date(post.date)
  const formattedDate = isNaN(published.getTime())
    ? post.date
    : published.toLocaleDateString(undefined, {
        year: 'numeric',
        month: 'long',
        day: 'numeric',
      })

  return (
    <>
      <Head>
        <title>{post.seoTitle}</title>
        <meta name="description" content={post.seoDescription} />
        <meta property="og:title" content={post.seoTitle} />
        <meta property="og:description" content={post.seoDescription} />
      </Head>
      <main className="max-w-3xl mx-auto px-4 py-8">
        <article className="w-full">
          <header className="mb-6">
            <h1 className="text-3xl sm:text-4xl font-bold mb-3">{post.title}</h1>
            <div className="text-sm text-gray-600 mb-4">
              <span>By {post.authorName}</span>
              {post.authorTitle ? <span> · {post.authorTitle}</span> : null}
              <span> · </span>
              <time dateTime={post.date}>{formattedDate}</time>
            </div>
            {post.tags && post.tags.length > 0 ? (
              <ul className="flex flex-wrap gap-2 mb-4" aria-label="Post tags">
                {post.tags.map((tag) => (
                  <li key={tag} className="text-xs bg-gray-100 text-gray-800 px-2 py-1 rounded">
                    {tag}
                  </li>
                ))}
              </ul>
            ) : null}
            {post.coverImage ? (
              <div className="mb-6">
                <img
                  src={post.coverImage}
                  alt={post.coverImageAlt}
                  className="w-full h-auto rounded-md"
                  loading="lazy"
                />
              </div>
            ) : null}
          </header>
          <section>
            <MarkdownRenderer content={post.body} />
          </section>
        </article>
      </main>
    </>
  )
}

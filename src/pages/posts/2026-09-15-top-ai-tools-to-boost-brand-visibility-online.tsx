function isExternalUrl(url: string) {
  try {
    const u = new URL(url);
    return u.protocol === 'http:' || u.protocol === 'https:';
  } catch {
    return false;
  }
}

function InlineMarkdown({ text }: { text: string }) {
  // Render inline markdown: links, code, bold, italic
  const tokens: React.ReactNode[] = [];
  const pattern = /(\[[^\]]+\]\([^\)]+\)|`[^`]+`|\*\*[^*]+\*\*|\*[^*]+\*)/g;
  let lastIndex = 0;
  const addText = (t: string) => {
    if (!t) return;
    tokens.push(t);
  };
  const input = text;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(input)) !== null) {
    const [full] = match;
    addText(input.slice(lastIndex, match.index));
    if (full.startsWith('[')) {
      const m = /^\[([^\]]+)\]\(([^\)]+)\)$/.exec(full);
      if (m) {
        const label = m[1];
        const href = m[2];
        const external = isExternalUrl(href);
        tokens.push(
          <a
            key={`a-${tokens.length}`}
            href={href}
            className="text-blue-600 underline underline-offset-2 hover:text-blue-700 focus:outline-none focus:ring-2 focus:ring-blue-400 rounded"
            {...(external ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
          >
            {label}
          </a>
        );
      } else {
        addText(full);
      }
    } else if (full.startsWith('`')) {
      tokens.push(
        <code key={`code-${tokens.length}`} className="px-1 py-0.5 rounded bg-gray-100 text-gray-800">
          {full.slice(1, -1)}
        </code>
      );
    } else if (full.startsWith('**')) {
      tokens.push(
        <strong key={`b-${tokens.length}`} className="font-semibold">{full.slice(2, -2)}</strong>
      );
    } else if (full.startsWith('*')) {
      tokens.push(
        <em key={`i-${tokens.length}`} className="italic">{full.slice(1, -1)}</em>
      );
    } else {
      addText(full);
    }
    lastIndex = pattern.lastIndex;
  }
  addText(input.slice(lastIndex));
  return <>{tokens}</>;
}

function MarkdownRenderer({ content }: { content: string }) {
  // Convert markdown to semantic HTML with utility classes, skipping the leading H1
  const lines = content.split(/\r?\n/);

  // Skip initial blank lines and one leading H1 if present
  let i = 0;
  while (i < lines.length && lines[i].trim() === '') i++;
  if (i < lines.length && /^#\s+/.test(lines[i])) {
    i++;
    if (i < lines.length && lines[i].trim() === '') i++;
  }

  const elements: React.ReactNode[] = [];

  const readParagraph = () => {
    const chunk: string[] = [];
    while (i < lines.length && lines[i].trim() !== '') {
      // Stop if next block starts (heading, list, blockquote, hr, table)
      if (/^(#{1,6})\s+/.test(lines[i])) break;
      if (/^>\s?/.test(lines[i])) break;
      if (/^(-|\*)\s+/.test(lines[i])) break;
      if (/^\d+\.\s+/.test(lines[i])) break;
      if (/^(-{3,}|\*{3,}|_{3,})\s*$/.test(lines[i])) break;
      // simple table detection
      if (/\|/.test(lines[i]) && i + 1 < lines.length && /^\s*\|?\s*:?[-]+:?/.test(lines[i + 1])) break;
      chunk.push(lines[i]);
      i++;
    }
    const text = chunk.join(' ').trim();
    if (text) {
      elements.push(
        <p key={`p-${i}-${elements.length}`} className="mb-4 leading-relaxed">
          <InlineMarkdown text={text} />
        </p>
      );
    }
  };

  const readHeading = () => {
    const m = /^(#{1,6})\s+(.*)$/.exec(lines[i]);
    if (!m) return false;
    const level = m[1].length;
    const text = m[2].trim();
    i++;
    const key = `h-${i}-${elements.length}`;
    if (level === 2) {
      elements.push(
        <h2 key={key} className="text-2xl font-bold mt-10 mb-4">
          <InlineMarkdown text={text} />
        </h2>
      );
    } else if (level === 3) {
      elements.push(
        <h3 key={key} className="text-xl font-semibold mt-8 mb-3">
          <InlineMarkdown text={text} />
        </h3>
      );
    } else if (level === 4) {
      elements.push(
        <h4 key={key} className="text-lg font-semibold mt-6 mb-2">
          <InlineMarkdown text={text} />
        </h4>
      );
    } else {
      // Map other heading levels to h3/h4 to keep hierarchy reasonable
      elements.push(
        <h3 key={key} className="text-xl font-semibold mt-8 mb-3">
          <InlineMarkdown text={text} />
        </h3>
      );
    }
    return true;
  };

  const readHR = () => {
    if (!/^(-{3,}|\*{3,}|_{3,})\s*$/.test(lines[i])) return false;
    i++;
    elements.push(<hr key={`hr-${i}-${elements.length}`} className="my-8 border-t" />);
    return true;
  };

  const readBlockquote = () => {
    if (!/^>\s?/.test(lines[i])) return false;
    const chunk: string[] = [];
    while (i < lines.length && /^>\s?/.test(lines[i])) {
      chunk.push(lines[i].replace(/^>\s?/, ''));
      i++;
    }
    const text = chunk.join(' ').trim();
    elements.push(
      <blockquote key={`bq-${i}-${elements.length}`} className="border-l-4 pl-4 italic my-6">
        <InlineMarkdown text={text} />
      </blockquote>
    );
    return true;
  };

  const readList = () => {
    if (!/^(-|\*)\s+/.test(lines[i]) && !/^\d+\.\s+/.test(lines[i])) return false;
    const ordered = /^\d+\.\s+/.test(lines[i]);
    const items: string[] = [];
    const matcher = ordered ? /^\d+\.\s+(.+)$/ : /^[-\*]\s+(.+)$/;
    while (i < lines.length) {
      const m = matcher.exec(lines[i]);
      if (!m) break;
      items.push(m[1]);
      i++;
    }
    const ListTag = ordered ? 'ol' : 'ul';
    elements.push(
      <ListTag key={`list-${i}-${elements.length}`} className={ordered ? 'list-decimal pl-6 mb-4 space-y-2' : 'list-disc pl-6 mb-4 space-y-2'}>
        {items.map((it, idx) => (
          <li key={`li-${idx}`} className="leading-relaxed"><InlineMarkdown text={it} /></li>
        ))}
      </ListTag>
    );
    return true;
  };

  const readTable = () => {
    // Very small pipe table support: header | header, divider, rows
    const hasPipes = lines[i].includes('|');
    const hasDividerNext = i + 1 < lines.length && /\|/.test(lines[i + 1]) && /[-:]/.test(lines[i + 1]);
    if (!hasPipes || !hasDividerNext) return false;
    const header = lines[i].split('|').map((s) => s.trim()).filter((s, idx, arr) => !(idx === 0 && s === '') && !(idx === arr.length - 1 && s === ''));
    i += 2; // skip header and divider
    const rows: string[][] = [];
    while (i < lines.length && /\|/.test(lines[i]) && lines[i].trim() !== '') {
      const cols = lines[i].split('|').map((s) => s.trim()).filter((s, idx, arr) => !(idx === 0 && s === '') && !(idx === arr.length - 1 && s === ''));
      rows.push(cols);
      i++;
    }
    elements.push(
      <div key={`table-${i}-${elements.length}`} className="overflow-x-auto my-6">
        <table className="w-full border-collapse">
          <thead>
            <tr>
              {header.map((h, idx) => (
                <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold"><InlineMarkdown text={h} /></th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row, rIdx) => (
              <tr key={`tr-${rIdx}`}>
                {row.map((c, cIdx) => (
                  <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left"><InlineMarkdown text={c} /></td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );
    return true;
  };

  while (i < lines.length) {
    if (lines[i].trim() === '') { i++; continue; }
    if (readHeading()) continue;
    if (readHR()) continue;
    if (readBlockquote()) continue;
    if (readList()) continue;
    if (readTable()) continue;
    readParagraph();
  }

  return <div>{elements}</div>;
}


function toPublicUrl(repoRelativePath: string): string {
  if (!repoRelativePath) return '';
  if (repoRelativePath.startsWith('public/')) return '/' + repoRelativePath.substring('public/'.length);
  if (repoRelativePath.startsWith('/')) return repoRelativePath;
  return '/' + repoRelativePath;
}

function parseInline(text: string, keyPrefix: string): Array<string | JSX.Element> {
  const nodes: Array<string | JSX.Element> = [];
  let remaining = text;
  let indexCounter = 0;

  type Match = { type: 'link' | 'code' | 'bold' | 'italic'; index: number; match: RegExpExecArray };

  const nextMatch = (s: string): Match | null => {
    const patterns: Array<{ type: Match['type']; regex: RegExp }> = [
      { type: 'link', regex: /\[([^\]]+)\]\(([^)]+)\)/ },
      { type: 'code', regex: /`([^`]+)`/ },
      { type: 'bold', regex: /\*\*([^*]+)\*\*/ },
      { type: 'italic', regex: /\*([^*]+)\*/ },
    ];
    let best: Match | null = null;
    for (const p of patterns) {
      const m = p.regex.exec(s);
      if (m) {
        if (best === null || m.index < best.index) {
          best = { type: p.type, index: m.index, match: m };
        }
      }
    }
    return best;
  };

  while (remaining.length > 0) {
    const m = nextMatch(remaining);
    if (!m) {
      nodes.push(remaining);
      break;
    }
    if (m.index > 0) {
      nodes.push(remaining.slice(0, m.index));
    }
    const [full, a, b] = m.match;
    switch (m.type) {
      case 'link':
        nodes.push(
          <a key={`${keyPrefix}-lnk-${indexCounter++}`} href={b} className="text-blue-600 underline" target="_blank" rel="noopener noreferrer">
            {a}
          </a>
        );
        break;
      case 'code':
        nodes.push(
          <code key={`${keyPrefix}-code-${indexCounter++}`} className="bg-gray-100 px-1 rounded text-sm">
            {a}
          </code>
        );
        break;
      case 'bold':
        nodes.push(
          <strong key={`${keyPrefix}-b-${indexCounter++}`} className="font-semibold">
            {a}
          </strong>
        );
        break;
      case 'italic':
        nodes.push(
          <em key={`${keyPrefix}-i-${indexCounter++}`} className="italic">
            {a}
          </em>
        );
        break;
    }
    remaining = remaining.slice(m.index + full.length);
  }
  return nodes;
}

const MarkdownRenderer: React.FC<{ content: string }> = ({ content }) => {
  const lines = content.split('\n');
  const elements: React.ReactNode[] = [];
  let i = 0;
  let key = 0;
  let skippedTitleH1 = false;

  const isTableSeparator = (line: string): boolean => {
    const trimmed = line.trim();
    if (!trimmed.includes('|')) return false;
    // Simple check for --- cells separated by |
    const parts = trimmed.split('|').map((p) => p.trim()).filter((p) => p.length > 0);
    if (parts.length === 0) return false;
    return parts.every((p) => /^:?-{3,}:?$/.test(p));
  };

  const splitRow = (row: string): string[] => {
    const raw = row.trim();
    const parts = raw.split('|');
    const cells: string[] = [];
    for (let idx = 0; idx < parts.length; idx++) {
      const cell = parts[idx];
      // skip leading/trailing empties when row starts/ends with |
      if ((idx === 0 || idx === parts.length - 1) && cell.trim() === '') continue;
      cells.push(cell.trim());
    }
    return cells;
  };

  const pushParagraph = (text: string) => {
    if (text.trim().length === 0) return;
    elements.push(
      <p key={`p-${key++}`} className="mb-4 leading-relaxed">
        {parseInline(text, `p-${key}`)}
      </p>
    );
  };

  while (i < lines.length) {
    let line = lines[i];

    // Skip empty lines
    if (line.trim() === '') {
      i++;
      continue;
    }

    // Table
    if (line.includes('|') && i + 1 < lines.length && isTableSeparator(lines[i + 1])) {
      const headerLine = line;
      const sepLine = lines[i + 1];
      void sepLine; // unused but kept for clarity
      i += 2;
      const rows: string[] = [];
      while (i < lines.length && lines[i].trim() !== '' && lines[i].includes('|')) {
        rows.push(lines[i]);
        i++;
      }
      const headers = splitRow(headerLine);
      const bodyRows = rows.map(splitRow);
      elements.push(
        <div key={`tbl-wrap-${key++}`} className="overflow-x-auto my-6">
          <table className="w-full border-collapse">
            <thead>
              <tr>
                {headers.map((h, idx) => (
                  <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold">
                    {parseInline(h, `th-${idx}`)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {bodyRows.map((r, rIdx) => (
                <tr key={`tr-${rIdx}`}>
                  {r.map((c, cIdx) => (
                    <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left">
                      {parseInline(c, `td-${rIdx}-${cIdx}`)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
      continue;
    }

    // Horizontal rule
    if (line.trim() === '---') {
      elements.push(<hr key={`hr-${key++}`} className="my-8 border-t" />);
      i++;
      continue;
    }

    // Headings
    const hMatch = /^(#{1,6})\s+(.*)$/.exec(line);
    if (hMatch) {
      const level = hMatch[1].length;
      const text = hMatch[2].trim();
      if (!skippedTitleH1 && level === 1 && elements.length === 0) {
        // Skip the leading H1 so it doesn't duplicate the page title
        skippedTitleH1 = true;
        i++;
        continue;
      }
      const common = { className: '' } as { className: string };
      let Tag: 'h2' | 'h3' | 'h4' = 'h2';
      if (level === 2) {
        common.className = 'text-2xl font-bold mt-10 mb-4';
        Tag = 'h2';
      } else if (level === 3) {
        common.className = 'text-xl font-semibold mt-8 mb-3';
        Tag = 'h3';
      } else {
        common.className = 'text-lg font-semibold mt-6 mb-2';
        Tag = 'h4';
      }
      elements.push(
        <Tag key={`h-${key++}`} className={common.className}>
          {parseInline(text, `h-${key}`)}
        </Tag>
      );
      i++;
      continue;
    }

    // Blockquote
    if (/^>\s+/.test(line)) {
      const parts: string[] = [];
      while (i < lines.length && /^>\s+/.test(lines[i])) {
        parts.push(lines[i].replace(/^>\s+/, ''));
        i++;
      }
      const quoteText = parts.join(' ');
      elements.push(
        <blockquote key={`bq-${key++}`} className="border-l-4 pl-4 italic my-6">
          {parseInline(quoteText, `bq-${key}`)}
        </blockquote>
      );
      continue;
    }

    // Lists - unordered
    if (/^\s*-\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*-\s+/.test(lines[i])) {
        const m = /^\s*-\s+(.*)$/.exec(lines[i]);
        items.push(m ? m[1] : lines[i].trim());
        i++;
      }
      elements.push(
        <ul key={`ul-${key++}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`uli-${idx}`}>{parseInline(it, `uli-${idx}`)}</li>
          ))}
        </ul>
      );
      continue;
    }

    // Lists - ordered
    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
        const m = /^\s*\d+\.\s+(.*)$/.exec(lines[i]);
        items.push(m ? m[1] : lines[i].trim());
        i++;
      }
      elements.push(
        <ol key={`ol-${key++}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`}>{parseInline(it, `oli-${idx}`)}</li>
          ))}
        </ol>
      );
      continue;
    }

    // Paragraph (collect until blank line)
    const para: string[] = [];
    while (i < lines.length && lines[i].trim() !== '') {
      para.push(lines[i]);
      i++;
    }
    pushParagraph(para.join(' '));
  }

  return <div>{elements}</div>;
};


function classNames(...c: Array<string | false | undefined | null>) {
  return c.filter(Boolean).join(' ')
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

function parseInline(text: string): (string | JSX.Element)[] {
  const nodes: (string | JSX.Element)[] = []
  let remaining = text

  const patterns = [
    { // links [text](url)
      regex: /\[([^\]]+)\]\(([^)]+)\)/,
      render: (m: RegExpExecArray) => (
        <a key={Math.random()} href={m[2]} className="text-blue-600 underline underline-offset-2 hover:text-blue-700 focus:outline-none focus:ring-2 focus:ring-blue-500" target={/^https?:\/\//.test(m[2]) ? '_blank' : undefined} rel={/^https?:\/\//.test(m[2]) ? 'noopener noreferrer' : undefined}>{m[1]}</a>
      )
    },
    { // code `code`
      regex: /`([^`]+)`/,
      render: (m: RegExpExecArray) => (
        <code key={Math.random()} className="px-1.5 py-0.5 rounded bg-gray-100 text-gray-800 font-mono text-sm">{m[1]}</code>
      )
    },
    { // bold **text** or __text__
      regex: /(\*\*|__)(.+?)\1/,
      render: (m: RegExpExecArray) => (
        <strong key={Math.random()} className="font-semibold">{parseInline(m[2])}</strong>
      )
    },
    { // italic *text* or _text_
      regex: /(\*|_)([^*_]+?)\1/,
      render: (m: RegExpExecArray) => (
        <em key={Math.random()} className="italic">{parseInline(m[2])}</em>
      )
    }
  ]

  outer: while (remaining.length > 0) {
    let earliest: { index: number; len: number; match: RegExpExecArray; render: (m: RegExpExecArray) => JSX.Element } | null = null
    for (const p of patterns) {
      const m = p.regex.exec(remaining)
      if (m && (earliest === null || m.index < earliest.index)) {
        earliest = { index: m.index, len: m[0].length, match: m as RegExpExecArray, render: p.render }
      }
    }
    if (!earliest) {
      nodes.push(remaining)
      break outer
    }
    if (earliest.index > 0) {
      nodes.push(remaining.slice(0, earliest.index))
    }
    nodes.push(earliest.render(earliest.match))
    remaining = remaining.slice(earliest.index + earliest.len)
  }

  return nodes
}

type Block = { type: 'h1' | 'h2' | 'h3' | 'p' | 'ul' | 'ol' | 'blockquote' | 'hr' | 'table'; content?: string; items?: string[]; table?: { header: string[]; rows: string[][] } }

function splitTableRow(line: string): string[] {
  // Trim edges and split by | keeping empty cells
  let trimmed = line.trim()
  if (trimmed.startsWith('|')) trimmed = trimmed.slice(1)
  if (trimmed.endsWith('|')) trimmed = trimmed.slice(0, -1)
  return trimmed.split('|').map(c => c.trim())
}

function removeLeadingH1(markdown: string): string {
  const lines = markdown.split('\n')
  let i = 0
  while (i < lines.length && lines[i].trim() === '') i++
  if (i < lines.length && /^#\s+/.test(lines[i])) {
    i++
    // skip a following blank line if present
    if (i < lines.length && lines[i].trim() === '') i++
    return lines.slice(i).join('\n')
  }
  return markdown
}

function parseBlocks(markdown: string): Block[] {
  const lines = markdown.split('\n')
  const blocks: Block[] = []
  let i = 0
  let paragraphBuffer: string[] = []
  let listType: 'ul' | 'ol' | null = null
  let listItems: string[] = []

  function flushParagraph() {
    if (paragraphBuffer.length) {
      const text = paragraphBuffer.join(' ').trim()
      if (text) blocks.push({ type: 'p', content: text })
      paragraphBuffer = []
    }
  }

  function flushList() {
    if (listType && listItems.length) {
      blocks.push({ type: listType, items: listItems })
    }
    listType = null
    listItems = []
  }

  while (i < lines.length) {
    let line = lines[i]
    const raw = line
    const trimmed = line.trim()

    // Horizontal rule
    if (/^\s*(---|\*\*\*|___)\s*$/.test(trimmed)) {
      flushParagraph()
      flushList()
      blocks.push({ type: 'hr' })
      i++
      continue
    }

    // Table detection: header | separated, next line a separator row
    if (trimmed.includes('|')) {
      const next = lines[i + 1]?.trim() ?? ''
      if (/^\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?$/.test(next)) {
        flushParagraph()
        flushList()
        const header = splitTableRow(trimmed)
        i += 2 // consume header and separator
        const rows: string[][] = []
        while (i < lines.length && lines[i].trim().includes('|') && !/^\s*$/.test(lines[i])) {
          rows.push(splitTableRow(lines[i]))
          i++
        }
        blocks.push({ type: 'table', table: { header, rows } })
        continue
      }
    }

    // Headings
    if (/^#{3}\s+/.test(trimmed)) {
      flushParagraph(); flushList()
      blocks.push({ type: 'h3', content: trimmed.replace(/^#{3}\s+/, '').trim() })
      i++
      continue
    }
    if (/^#{2}\s+/.test(trimmed)) {
      flushParagraph(); flushList()
      blocks.push({ type: 'h2', content: trimmed.replace(/^#{2}\s+/, '').trim() })
      i++
      continue
    }
    if (/^#\s+/.test(trimmed)) {
      // h1 in body shouldn't normally appear (we remove the first), but handle just in case
      flushParagraph(); flushList()
      blocks.push({ type: 'h1', content: trimmed.replace(/^#\s+/, '').trim() })
      i++
      continue
    }

    // Blockquote
    if (/^\s*>\s?/.test(raw)) {
      flushParagraph(); flushList()
      const quoteLines: string[] = []
      while (i < lines.length && /^\s*>\s?/.test(lines[i])) {
        quoteLines.push(lines[i].replace(/^\s*>\s?/, ''))
        i++
      }
      const content = quoteLines.join(' ').trim()
      blocks.push({ type: 'blockquote', content })
      continue
    }

    // List items
    const listMatch = raw.match(/^\s*([-+*])\s+(.+)$/) || raw.match(/^\s*(\d+)\.\s+(.+)$/)
    if (listMatch) {
      const isOrdered = /\d+\./.test(listMatch[0])
      const itemText = (listMatch[2] || listMatch[1]) ? (listMatch[2] || listMatch[1]) : ''
      if (!listType) {
        flushParagraph()
        listType = isOrdered ? 'ol' : 'ul'
        listItems = []
      }
      // If list type switches, flush and start new
      if ((isOrdered ? 'ol' : 'ul') !== listType) {
        flushList()
        listType = isOrdered ? 'ol' : 'ul'
      }
      listItems.push(itemText.trim())
      i++
      // keep consuming contiguous list items
      continue
    }

    // Blank line ends paragraph or list
    if (trimmed === '') {
      flushParagraph(); flushList()
      i++
      continue
    }

    // Paragraph text (append)
    paragraphBuffer.push(trimmed)
    i++
  }

  // Flush remaining buffers
  flushParagraph()
  flushList()

  return blocks
}

function MarkdownRenderer({ content }: { content: string }) {
  const blocks = useMemo(() => parseBlocks(content), [content])

  return (
    <div>
      {blocks.map((block, idx) => {
        switch (block.type) {
          case 'h1':
            return <h2 key={idx} className="text-2xl font-bold mt-10 mb-4">{parseInline(block.content || '')}</h2>
          case 'h2':
            return <h2 key={idx} className="text-2xl font-bold mt-10 mb-4">{parseInline(block.content || '')}</h2>
          case 'h3':
            return <h3 key={idx} className="text-xl font-semibold mt-8 mb-3">{parseInline(block.content || '')}</h3>
          case 'p':
            return <p key={idx} className="mb-4 leading-relaxed">{parseInline(block.content || '')}</p>
          case 'ul':
            return (
              <ul key={idx} className="list-disc pl-6 mb-4 space-y-2">
                {(block.items || []).map((it, i2) => (
                  <li key={i2} className="marker:text-gray-700">{parseInline(it)}</li>
                ))}
              </ul>
            )
          case 'ol':
            return (
              <ol key={idx} className="list-decimal pl-6 mb-4 space-y-2">
                {(block.items || []).map((it, i2) => (
                  <li key={i2} className="marker:text-gray-700">{parseInline(it)}</li>
                ))}
              </ol>
            )
          case 'blockquote':
            return (
              <blockquote key={idx} className="border-l-4 pl-4 italic my-6 text-gray-800">{parseInline(block.content || '')}</blockquote>
            )
          case 'hr':
            return <hr key={idx} className="my-8 border-gray-200" />
          case 'table':
            return (
              <div key={idx} className="overflow-x-auto my-6">
                <table className="w-full border-collapse text-left text-sm">
                  <thead>
                    <tr>
                      {(block.table?.header || []).map((h, i2) => (
                        <th key={i2} className="border px-3 py-2 font-semibold bg-gray-50">{parseInline(h)}</th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {(block.table?.rows || []).map((row, rIdx) => (
                      <tr key={rIdx} className={classNames(rIdx % 2 === 0 && 'bg-white', rIdx % 2 === 1 && 'bg-gray-50')}>
                        {row.map((cell, cIdx) => (
                          <td key={cIdx} className="border px-3 py-2 align-top">{parseInline(cell)}</td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )
          default:
            return null
        }
      })}
    </div>
  )
}


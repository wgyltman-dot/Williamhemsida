// Simple local Markdown renderer with styled, semantic output and leading H1 skip
function MarkdownRenderer({ content }: { content: string }) {
  type InlineNode = string | JSX.Element;

  const renderInline = (text: string): InlineNode[] => {
    const nodes: InlineNode[] = [];
    let pos = 0;

    const patterns: { type: "link" | "code" | "bold" | "italic"; regex: RegExp }[] = [
      { type: "link", regex: /\[([^\]]+)\]\(([^)]+)\)/ },
      { type: "code", regex: /`([^`]+)`/ },
      { type: "bold", regex: /\*\*([^*]+)\*\*/ },
      { type: "italic", regex: /\*([^*]+)\*/ },
    ];

    while (pos < text.length) {
      let best:
        | { type: "link" | "code" | "bold" | "italic"; match: RegExpMatchArray; index: number }
        | null = null;

      const slice = text.slice(pos);
      for (const p of patterns) {
        const m = slice.match(p.regex);
        if (m && typeof (m as RegExpMatchArray & { index?: number }).index === "number") {
          const idx = (m as RegExpMatchArray & { index?: number }).index as number;
          if (best === null || idx < best.index) {
            best = { type: p.type, match: m, index: idx };
          }
        }
      }

      if (!best) {
        nodes.push(text.slice(pos));
        break;
      }

      if (best.index > 0) {
        nodes.push(text.slice(pos, pos + best.index));
      }

      const full = best.match[0];
      const inner = best.match[1];
      switch (best.type) {
        case "link": {
          const href = best.match[2];
          nodes.push(
            <a key={`${pos}-a`} href={href} target="_blank" rel="noopener noreferrer" className="text-blue-600 underline">
              {inner}
            </a>
          );
          break;
        }
        case "code":
          nodes.push(
            <code key={`${pos}-code`} className="bg-gray-100 rounded px-1 py-0.5 font-mono text-sm">
              {inner}
            </code>
          );
          break;
        case "bold":
          nodes.push(
            <strong key={`${pos}-b`} className="font-semibold">
              {inner}
            </strong>
          );
          break;
        case "italic":
          nodes.push(
            <em key={`${pos}-i`} className="italic">
              {inner}
            </em>
          );
          break;
      }

      pos += best.index + full.length;
    }

    return nodes;
  };

  const parseTableRow = (line: string): string[] => {
    const trimmed = line.trim().replace(/^\|/, "").replace(/\|$/, "");
    return trimmed.split("|").map((c) => c.trim());
  };

  const elements: JSX.Element[] = [];
  const lines = content.split(/\r?\n/);
  let i = 0;
  let skippedLeadingH1 = false;

  const isTableSeparator = (line: string) => /\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?/u.test(line.trim());

  while (i < lines.length) {
    let line = lines[i];

    // Skip empty lines
    if (line.trim() === "") {
      i++;
      continue;
    }

    // Leading H1 skip
    if (!skippedLeadingH1 && line.startsWith("# ")) {
      skippedLeadingH1 = true;
      i++;
      continue;
    }

    // Headings
    if (line.startsWith("### ")) {
      const text = line.replace(/^###\s+/, "");
      elements.push(
        <h3 key={`h3-${i}`} className="text-xl font-semibold mt-8 mb-3">
          {renderInline(text)}
        </h3>
      );
      i++;
      continue;
    }
    if (line.startsWith("## ")) {
      const text = line.replace(/^##\s+/, "");
      elements.push(
        <h2 key={`h2-${i}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(text)}
        </h2>
      );
      i++;
      continue;
    }

    // Horizontal rule
    if (line.trim() === "---") {
      elements.push(<hr key={`hr-${i}`} className="my-8 border-t border-gray-200" />);
      i++;
      continue;
    }

    // Blockquote
    if (line.startsWith("> ")) {
      const quoteLines: string[] = [];
      while (i < lines.length && lines[i].startsWith("> ")) {
        quoteLines.push(lines[i].replace(/^>\s?/, ""));
        i++;
      }
      const quoteText = quoteLines.join(" ");
      elements.push(
        <blockquote key={`bq-${i}`} className="border-l-4 border-gray-300 pl-4 italic my-6 text-gray-700">
          <p className="leading-relaxed">{renderInline(quoteText)}</p>
        </blockquote>
      );
      continue;
    }

    // Tables
    if (
      line.includes("|") &&
      i + 1 < lines.length &&
      lines[i + 1].includes("|") &&
      (isTableSeparator(lines[i + 1]) || /---/.test(lines[i + 1]))
    ) {
      const header = parseTableRow(line);
      const sepLine = lines[i + 1];
      // consume header + separator
      i += 2;
      const bodyRows: string[][] = [];
      while (i < lines.length && lines[i].includes("|")) {
        const row = parseTableRow(lines[i]);
        bodyRows.push(row);
        i++;
      }
      elements.push(
        <table key={`tbl-${i}`} className="w-full border-collapse my-6 text-sm">
          <thead>
            <tr>
              {header.map((h, idx) => (
                <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold bg-gray-50">
                  {renderInline(h)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {bodyRows.map((row, r) => (
              <tr key={`tr-${r}`}>
                {row.map((cell, c) => (
                  <td key={`td-${r}-${c}`} className="border px-3 py-2 align-top">
                    {renderInline(cell)}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      );
      continue;
    }

    // Lists: unordered
    if (/^\s*-\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*-\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*-\s+/, ""));
        i++;
      }
      elements.push(
        <ul key={`ul-${i}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`li-${idx}`} className="leading-relaxed">
              {renderInline(it)}
            </li>
          ))}
        </ul>
      );
      continue;
    }

    // Lists: ordered
    if (/^\s*\d+\.\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*\d+\.\s+/, ""));
        i++;
      }
      elements.push(
        <ol key={`ol-${i}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`} className="leading-relaxed">
              {renderInline(it)}
            </li>
          ))}
        </ol>
      );
      continue;
    }

    // Paragraph (collect until blank line or new block)
    const paraLines: string[] = [line];
    i++;
    while (
      i < lines.length &&
      lines[i].trim() !== "" &&
      !lines[i].startsWith("## ") &&
      !lines[i].startsWith("### ") &&
      !/^\s*-\s+/.test(lines[i]) &&
      !/^\s*\d+\.\s+/.test(lines[i]) &&
      !lines[i].startsWith("> ") &&
      !(lines[i].includes("|") && i + 1 < lines.length && /---/.test(lines[i + 1])) &&
      lines[i].trim() !== "---"
    ) {
      paraLines.push(lines[i]);
      i++;
    }
    const paraText = paraLines.join(" ").trim();
    elements.push(
      <p key={`p-${i}-${paraText.slice(0, 10)}`} className="mb-4 leading-relaxed">
        {renderInline(paraText)}
      </p>
    );
  }

  return <div>{elements}</div>;
}


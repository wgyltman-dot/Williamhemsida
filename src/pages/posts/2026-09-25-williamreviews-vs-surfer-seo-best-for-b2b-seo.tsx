function renderInline(text: string): Array<string | JSX.Element> {
  // Handle code spans first by splitting on backticks
  const parts = text.split('`')
  const nodes: Array<string | JSX.Element> = []
  parts.forEach((part, idx) => {
    if (idx % 2 === 1) {
      nodes.push(
        <code key={`code-${idx}`} className="px-1 py-0.5 rounded bg-gray-100 text-sm">
          {part}
        </code>
      )
    } else {
      // Process links [text](url)
      let remaining = part
      const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g
      let lastIndex = 0
      let match: RegExpExecArray | null
      while ((match = linkRegex.exec(part)) !== null) {
        const before = part.slice(lastIndex, match.index)
        if (before) nodes.push(before)
        const linkText = match[1]
        const href = match[2]
        nodes.push(
          <a
            key={`lnk-${idx}-${match.index}`}
            href={href}
            className="text-blue-600 underline hover:text-blue-700"
            rel="nofollow noopener noreferrer"
          >
            {linkText}
          </a>
        )
        lastIndex = match.index + match[0].length
      }
      const tail = part.slice(lastIndex)
      if (tail) {
        // Bold **text** then italic *text*
        const boldParts = tail.split('**')
        boldParts.forEach((bp, bIdx) => {
          if (bIdx % 2 === 1) {
            nodes.push(
              <strong key={`b-${idx}-${bIdx}`} className="font-semibold">
                {bp}
              </strong>
            )
          } else {
            const italParts = bp.split('*')
            italParts.forEach((ip, iIdx) => {
              if (iIdx % 2 === 1) {
                nodes.push(
                  <em key={`i-${idx}-${bIdx}-${iIdx}`} className="italic">
                    {ip}
                  </em>
                )
              } else {
                if (ip) nodes.push(ip)
              }
            })
          }
        })
      }
    }
  })
  return nodes
}

function parseTableRow(line: string): string[] {
  const trimmed = line.trim()
  const noEdges = trimmed.replace(/^\|/, '').replace(/\|$/, '')
  return noEdges.split('|').map((c) => c.trim())
}

function MarkdownRenderer({ content }: { content: string }) {
  const blocks: React.ReactNode[] = []
  const lines = content.split('\n')

  // Skip leading H1 to avoid duplicate page title
  let i = 0
  while (i < lines.length && lines[i].trim() === '') i++
  if (i < lines.length && /^#\s+/.test(lines[i])) i++

  const pushParagraph = (buf: string[]) => {
    if (buf.length === 0) return
    const text = buf.join(' ').trim()
    if (text)
      blocks.push(
        <p key={`p-${blocks.length}`} className="mb-4 leading-relaxed">
          {renderInline(text)}
        </p>
      )
  }

  while (i < lines.length) {
    const line = lines[i]
    const trimmed = line.trim()

    // Blank line -> paragraph separator
    if (trimmed === '') {
      i++
      continue
    }

    // Headings
    if (/^###\s+/.test(trimmed)) {
      blocks.push(
        <h3 key={`h3-${blocks.length}`} className="text-xl font-semibold mt-8 mb-3">
          {renderInline(trimmed.replace(/^###\s+/, ''))}
        </h3>
      )
      i++
      continue
    }
    if (/^##\s+/.test(trimmed)) {
      blocks.push(
        <h2 key={`h2-${blocks.length}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(trimmed.replace(/^##\s+/, ''))}
        </h2>
      )
      i++
      continue
    }

    // Horizontal rule
    if (/^---+$/.test(trimmed)) {
      blocks.push(<hr key={`hr-${blocks.length}`} className="my-8 border-t" />)
      i++
      continue
    }

    // Blockquote
    if (/^>\s?/.test(trimmed)) {
      const bq: string[] = []
      while (i < lines.length && /^>\s?/.test(lines[i].trim())) {
        bq.push(lines[i].trim().replace(/^>\s?/, ''))
        i++
      }
      blocks.push(
        <blockquote key={`bq-${blocks.length}`} className="border-l-4 pl-4 italic my-6">
          {renderInline(bq.join(' '))}
        </blockquote>
      )
      continue
    }

    // Unordered list
    if (/^-\s+/.test(trimmed)) {
      const items: string[] = []
      while (i < lines.length && /^-\s+/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^-\s+/, ''))
        i++
      }
      blocks.push(
        <ul key={`ul-${blocks.length}`} className="list-disc pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`li-${idx}`} className="ml-1">
              {renderInline(it)}
            </li>
          ))}
        </ul>
      )
      continue
    }

    // Ordered list (1. )
    if (/^\d+\.\s+/.test(trimmed)) {
      const items: string[] = []
      while (i < lines.length && /^\d+\.\s+/.test(lines[i].trim())) {
        const m = lines[i].trim().replace(/^\d+\.\s+/, '')
        items.push(m)
        i++
      }
      blocks.push(
        <ol key={`ol-${blocks.length}`} className="list-decimal pl-6 mb-4 space-y-2">
          {items.map((it, idx) => (
            <li key={`oli-${idx}`} className="ml-1">
              {renderInline(it)}
            </li>
          ))}
        </ol>
      )
      continue
    }

    // Table
    if (trimmed.includes('|')) {
      const next = lines[i + 1]?.trim() ?? ''
      if (next.includes('|') && /\|?\s*-{3,}\s*(\|\s*-{3,}\s*)+\|?/.test(next)) {
        // header row and separator
        const headerCells = parseTableRow(trimmed)
        i += 2 // skip header and separator
        const rows: string[][] = []
        while (i < lines.length && lines[i].trim().includes('|') && !/^\s*$/.test(lines[i])) {
          rows.push(parseTableRow(lines[i]))
          i++
        }
        blocks.push(
          <table key={`tbl-${blocks.length}`} className="w-full border-collapse my-6">
            <thead>
              <tr>
                {headerCells.map((c, idx) => (
                  <th key={`th-${idx}`} className="border px-3 py-2 text-left font-semibold">
                    {renderInline(c)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {rows.map((r, rIdx) => (
                <tr key={`tr-${rIdx}`}>
                  {r.map((c, cIdx) => (
                    <td key={`td-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left">
                      {renderInline(c)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        )
        continue
      }
    }

    // Paragraph (collect consecutive non-empty lines until a blank or special block)
    const buf: string[] = []
    while (
      i < lines.length &&
      lines[i].trim() !== '' &&
      !/^##\s+/.test(lines[i].trim()) &&
      !/^###\s+/.test(lines[i].trim()) &&
      !/^>\s?/.test(lines[i].trim()) &&
      !/^-\s+/.test(lines[i].trim()) &&
      !/^\d+\.\s+/.test(lines[i].trim()) &&
      !/^---+$/.test(lines[i].trim())
    ) {
      buf.push(lines[i].trim())
      i++
    }
    pushParagraph(buf)
  }

  return <div>{blocks}</div>
}


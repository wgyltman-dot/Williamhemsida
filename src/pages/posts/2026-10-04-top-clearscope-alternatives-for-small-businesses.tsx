function formatDate(iso: string): string {
  try {
    const d = new Date(iso)
    return d.toLocaleDateString(undefined, {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    })
  } catch {
    return iso
  }
}

function MarkdownRenderer({ content }: { content: string }) {
  const elements: React.ReactNode[] = []
  const lines = content.split('\n')

  let i = 0
  let listType: 'ul' | 'ol' | null = null
  let listItems: string[] = []
  let blockquoteLines: string[] = []
  let paragraphLines: string[] = []
  let tableLines: string[] = []
  let skippingFirstH1 = true
  let keyCounter = 0

  const flushParagraph = () => {
    if (paragraphLines.length > 0) {
      const text = paragraphLines.join(' ')
      elements.push(
        <p key={`p-${keyCounter++}`} className="mb-4 leading-relaxed">
          {renderInline(text)}
        </p>
      )
      paragraphLines = []
    }
  }

  const flushList = () => {
    if (listType && listItems.length > 0) {
      const ListTag = listType === 'ul' ? 'ul' : 'ol'
      elements.push(
        <ListTag
          key={`list-${keyCounter++}`}
          className={listType === 'ul' ? 'list-disc pl-6 mb-4 space-y-2' : 'list-decimal pl-6 mb-4 space-y-2'}
        >
          {listItems.map((li, idx) => (
            <li key={`li-${keyCounter++}-${idx}`}>{renderInline(li)}</li>
          ))}
        </ListTag>
      )
      listType = null
      listItems = []
    }
  }

  const flushBlockquote = () => {
    if (blockquoteLines.length > 0) {
      const text = blockquoteLines.join(' ')
      elements.push(
        <blockquote key={`bq-${keyCounter++}`} className="border-l-4 pl-4 italic my-6">
          {renderInline(text)}
        </blockquote>
      )
      blockquoteLines = []
    }
  }

  const flushTable = () => {
    if (tableLines.length > 0) {
      const rows = tableLines.map((l) => l.trim().replace(/^\|/, '').replace(/\|$/, ''))
      const header = rows[0]?.split('|').map((c) => c.trim()) || []
      const bodyRows = rows.slice(2).map((r) => r.split('|').map((c) => c.trim()))
      elements.push(
        <div key={`table-wrap-${keyCounter++}`} className="overflow-x-auto my-6">
          <table className="w-full border-collapse my-0">
            <thead>
              <tr>
                {header.map((h, idx) => (
                  <th key={`th-${keyCounter++}-${idx}`} className="border px-3 py-2 text-left text-sm font-semibold">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {bodyRows.map((cells, rIdx) => (
                <tr key={`tr-${keyCounter++}-${rIdx}`}>
                  {cells.map((c, cIdx) => (
                    <td key={`td-${keyCounter++}-${rIdx}-${cIdx}`} className="border px-3 py-2 text-left">
                      {renderInline(c)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )
      tableLines = []
    }
  }

  const isTableLine = (line: string) => line.trim().startsWith('|') && line.includes('|')

  while (i < lines.length) {
    const line = lines[i]
    const trimmed = line.trim()

    // Handle table blocks
    if (isTableLine(line)) {
      flushParagraph()
      flushList()
      flushBlockquote()
      if (tableLines.length === 0) {
        tableLines.push(line)
      } else {
        tableLines.push(line)
      }
      // Lookahead to see if next line is still table
      const next = lines[i + 1]
      if (!next || !isTableLine(next)) {
        // completed table block
        flushTable()
      }
      i++
      continue
    }

    // Blank line indicates paragraph/list/blockquote separation
    if (trimmed === '') {
      flushTable()
      flushParagraph()
      flushList()
      flushBlockquote()
      i++
      continue
    }

    // Headings
    if (trimmed.startsWith('# ')) {
      // Leading H1 should be skipped
      if (skippingFirstH1) {
        skippingFirstH1 = false
      } else {
        flushParagraph()
        elements.push(
          <h1 key={`h1-${keyCounter++}`} className="text-3xl font-bold mt-12 mb-4">
            {renderInline(trimmed.replace(/^#\s+/, ''))}
          </h1>
        )
      }
      i++
      continue
    }
    if (trimmed.startsWith('## ')) {
      skippingFirstH1 = false
      flushParagraph()
      elements.push(
        <h2 key={`h2-${keyCounter++}`} className="text-2xl font-bold mt-10 mb-4">
          {renderInline(trimmed.replace(/^##\s+/, ''))}
        </h2>
      )
      i++
      continue
    }
    if (trimmed.startsWith('### ')) {
      skippingFirstH1 = false
      flushParagraph()
      elements.push(
        <h3 key={`h3-${keyCounter++}`} className="text-xl font-semibold mt-8 mb-3">
          {renderInline(trimmed.replace(/^###\s+/, ''))}
        </h3>
      )
      i++
      continue
    }

    // Horizontal rule
    if (/^---+$/.test(trimmed)) {
      flushParagraph()
      elements.push(<hr key={`hr-${keyCounter++}`} className="my-6 border-t" />)
      i++
      continue
    }

    // Blockquote
    if (trimmed.startsWith('> ')) {
      flushParagraph()
      blockquoteLines.push(trimmed.replace(/^>\s?/, ''))
      // If next line isn't another blockquote, flush
      const next = lines[i + 1]
      if (!next || !next.trim().startsWith('> ')) {
        flushBlockquote()
      }
      i++
      continue
    }

    // Lists
    const olMatch = trimmed.match(/^(\d+)\.\s+(.*)$/)
    if (trimmed.startsWith('- ')) {
      flushParagraph()
      if (listType && listType !== 'ul') {
        flushList()
      }
      listType = 'ul'
      listItems.push(trimmed.replace(/^-\s+/, ''))
      // If next line is not a list item, flush
      const next = lines[i + 1]
      if (!next || !next.trim().startsWith('- ')) {
        flushList()
      }
      i++
      continue
    } else if (olMatch) {
      flushParagraph()
      if (listType && listType !== 'ol') {
        flushList()
      }
      listType = 'ol'
      listItems.push(olMatch[2])
      const next = lines[i + 1]
      const nextMatch = next && next.trim().match(/^(\d+)\.\s+(.*)$/)
      if (!next || !nextMatch) {
        flushList()
      }
      i++
      continue
    }

    // Default: paragraph line (collect until blank)
    paragraphLines.push(line)
    i++
  }

  // Flush any remaining buffers
  flushTable()
  flushParagraph()
  flushList()
  flushBlockquote()

  return <div>{elements}</div>
}

function renderInline(text: string): React.ReactNode[] {
  // Linkify URLs and apply simple inline code styling
  const nodes: React.ReactNode[] = []
  const urlRegex = /(https?:\/\/[^\s)]+)/g

  // Split by backtick code spans first
  const codeSplit = text.split(/(`[^`]+`)/g)
  codeSplit.forEach((segment, idx) => {
    if (segment.startsWith('`') && segment.endsWith('`')) {
      const codeText = segment.slice(1, -1)
      nodes.push(
        <code key={`code-${idx}`} className="bg-gray-100 rounded px-1 py-0.5 font-mono text-sm">
          {codeText}
        </code>
      )
    } else {
      // Linkify URLs inside this non-code segment
      const parts = segment.split(urlRegex)
      parts.forEach((part, pIdx) => {
        if (urlRegex.test(part)) {
          nodes.push(
            <a
              key={`a-${idx}-${pIdx}`}
              href={part}
              className="text-blue-600 underline hover:text-blue-800"
              target="_blank"
              rel="nofollow noopener noreferrer"
            >
              {part}
            </a>
          )
        } else {
          // Bold and italic minimal support
          const boldSplit = part.split(/(\*\*[^*]+\*\*)/g)
          boldSplit.forEach((bseg, bIdx) => {
            if (bseg.startsWith('**') && bseg.endsWith('**')) {
              nodes.push(
                <strong key={`b-${idx}-${pIdx}-${bIdx}`} className="font-semibold">
                  {bseg.slice(2, -2)}
                </strong>
              )
            } else {
              const italSplit = bseg.split(/(\*[^*]+\*)/g)
              italSplit.forEach((iseg, iIdx) => {
                if (iseg.startsWith('*') && iseg.endsWith('*')) {
                  nodes.push(
                    <em key={`i-${idx}-${pIdx}-${bIdx}-${iIdx}`} className="italic">
                      {iseg.slice(1, -1)}
                    </em>
                  )
                } else if (iseg) {
                  nodes.push(<React.Fragment key={`t-${idx}-${pIdx}-${bIdx}-${iIdx}`}>{iseg}</React.Fragment>)
                }
              })
            }
          })
        }
      })
    }
  })

  return nodes
}

